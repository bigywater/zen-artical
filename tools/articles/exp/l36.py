sh(d, 'git worktree unlock ../l36wt1; git worktree move ../l36wt1 ../l36mv; cat ../l36mv/.git | sed -E "s#.*/ltmp#<ltmp>#"; cat .git/worktrees/l36wt1/gitdir | sed -E "s#.*/ltmp#<ltmp>#"')
sh(d, 'git worktree remove ../l36mv 2>&1; ls .git/worktrees 2>&1 | head -1; git worktree list | wc -l')
