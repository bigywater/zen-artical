import sys, os; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from ll import *
tee('l11')
CR = 'line1\r\nline2\r\n'; LF = 'line1\nline2\n'
def blobraw(d, spec): return loose(d, out1(d, f'git rev-parse {spec}')).split(b'\0', 1)[1]
print('== 一:默认(autocrlf 未设置):原样存,blob 里就是 CRLF')
d = lab('l11a'); W(d, {'win.txt': CR, 'unix.txt': LF})
sh(d, 'git config --get core.autocrlf || echo "(未设置)"; git config core.eol || echo "core.eol 未设置(默认 native,macOS 上是 LF)"')
sh(d, 'git add -A && git ls-files --eol')
print('  blob 原始字节:', blobraw(d, ':win.txt'), blobraw(d, ':unix.txt'))
print('== 二:core.autocrlf=true:add 时 CRLF→LF,checkout 时 LF→CRLF')
d = lab('l11b'); sh(d, 'git config core.autocrlf true', show=False)
W(d, {'win.txt': CR, 'unix.txt': LF})
sh(d, 'git add -A 2>&1; git ls-files --eol')
print('  blob 原始字节(win.txt / unix.txt):', blobraw(d, ':win.txt'), blobraw(d, ':unix.txt'))
sh(d, 'git commit -q -m x; rm win.txt unix.txt; git checkout -- win.txt unix.txt; git ls-files --eol')
print('  检出后工作区文件的字节:', (d / 'win.txt').read_bytes(), (d / 'unix.txt').read_bytes())
sh(d, 'git status --short; echo "(status 为空:工作区的 CRLF 与 blob 的 LF 被视为相同)"')
print('== 三:core.autocrlf=input:add 时 CRLF→LF,checkout 时不转换(Linux / macOS 常用)')
d = lab('l11c'); sh(d, 'git config core.autocrlf input', show=False)
W(d, {'win.txt': CR, 'unix.txt': LF})
sh(d, 'git add -A 2>&1; git ls-files --eol')
print('  blob 原始字节:', blobraw(d, ':win.txt'), blobraw(d, ':unix.txt'))
print('== 四:.gitattributes 的 text / eol / binary 优先于 autocrlf,而且随仓库走')
d = lab('l11d'); sh(d, 'git config core.autocrlf false', show=False)
W(d, {'.gitattributes': '*.txt text\n*.bat text eol=crlf\n*.sh text eol=lf\n*.bin binary\n', 'a.txt': CR, 'b.bat': LF, 'c.sh': CR, 'd.bin': CR, 'e.dat': CR})
sh(d, 'git add -A 2>&1; git ls-files --eol')
print('  blob 原始字节:'); [print(f'    {f}: {blobraw(d, ":" + f)!r}') for f in ['a.txt', 'b.bat', 'c.sh', 'd.bin', 'e.dat']]
sh(d, 'git commit -q -m x; rm b.bat c.sh a.txt; git checkout -- b.bat c.sh a.txt; git ls-files --eol')
print('== 五:已提交的 CRLF 文件,后来加了 text 属性:要 --renormalize 才会重新规范')
d = lab('l11e'); W(d, {'old.txt': CR}); ci(d, '先提交了 CRLF', t=0)
sh(d, "git ls-files --eol; printf '*.txt text\\n' > .gitattributes; git add .gitattributes; git status --short")
sh(d, 'git add --renormalize . ; git status --short; git diff --cached --stat; git ls-files --eol')
print('== 六:safecrlf:转换不可逆时拒绝(混合换行的文件)')
d = lab('l11f'); sh(d, 'git config core.autocrlf true; git config core.safecrlf true', show=False)
W(d, {'mix.txt': 'a\r\nb\nc\r\n'})
sh(d, 'git add mix.txt 2>&1; git ls-files -s mix.txt; echo "(退出情况见上)"')
sh(d, 'git config core.safecrlf warn; git add mix.txt 2>&1; git ls-files --eol mix.txt')
W(d, {'bin.dat': b'\x00\x01a\r\nb\r\n'})
sh(d, 'git add bin.dat 2>&1; git ls-files --eol bin.dat')
