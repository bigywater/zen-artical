import sys, os, json; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from ml import *
tee('m73'); reset()
nd = Node('m73').start(); c = nd.client()
c.test.t.insert_many([{'_id': i, 'k': i % 100, 'p': 'x' * 100} for i in range(50000)], ordered=False)
c.test.command('create', 'small'); c.test.small.insert_one({'_id': 1})
print('== 一:默认值:profile 级别 0(不记录到 system.profile),slowOpThresholdMs = 100;慢于阈值的操作会写进 mongod 日志')
msh(nd, "db.getProfilingStatus()", n=6)
msh(nd, "db.system.profile.countDocuments({})", n=3)
print('== 二:一个没有索引的查询(扫描 5 万个文档),先看默认阈值 100 ms 下日志里有没有它;再把 slowms 调到 5 ms(每次循环有一个 find 和一个 getMore,toArray 要拉完 5 万个文档)')
def slowlogs(): return [l for l in nd.logs() if l.get('msg') == 'Slow query']
n0 = len(slowlogs())
msh0(nd, "for (let i = 0; i < 20; i++) db.t.find({p: 'x'.repeat(100), k: {$gte: 0}}).sort({k: -1}).toArray().length")
print(f'  阈值 100 ms:跑了 20 次全表扫描后,日志里新增的 "Slow query" 数 = {len(slowlogs()) - n0}')
msh(nd, "db.setProfilingLevel(0, {slowms: 5})", n=4)
n1 = len(slowlogs())
msh0(nd, "for (let i = 0; i < 20; i++) db.t.find({p: 'x'.repeat(100), k: {$gte: 0}}).sort({k: -1}).toArray().length")
new = slowlogs()[n1:]; from collections import Counter
print(f'  阈值 5 ms:同样的 20 次之后,新增 "Slow query" = {len(new)}  按命令分: {dict(Counter(list(x["attr"]["command"].keys())[0] for x in new))}')
sl = [x for x in new if 'find' in x['attr']['command']][-1]['attr']
print('  最后一条 find 的 Slow query 日志的字段: ' + str(sorted(sl.keys())))
print('  其中 durationMillis = ' + str(sl.get('durationMillis')) + ',docsExamined = ' + str(sl.get('docsExamined')) + ',planSummary = ' + str(sl.get('planSummary')) + ',keysExamined = ' + str(sl.get('keysExamined')) + ',nreturned = ' + str(sl.get('nreturned')))
print('== 三:profile 级别 1(只记慢操作)和 2(记所有操作)到 system.profile')
msh(nd, "db.setProfilingLevel(1, {slowms: 5})", n=4)
msh0(nd, "for (let i = 0; i < 5; i++) db.t.find({p: 'x'.repeat(100), k: {$gte: 0}}).sort({k: -1}).toArray().length; db.small.findOne({_id: 1})")
msh(nd, "db.system.profile.aggregate([{$group: {_id: {op: '$op', ns: '$ns', plan: '$planSummary'}, n: {$sum: 1}, maxMillis: {$max: '$millis'}}}, {$sort: {'_id.op': 1}}]).toArray()", n=30)
msh(nd, "db.system.profile.countDocuments({ns: 'test.small'})", n=3, label="db.system.profile.countDocuments({ns: 'test.small'})  // findOne 很快,级别 1 没记录")
msh(nd, "db.setProfilingLevel(2)", n=4)
msh(nd, "db.small.findOne({_id: 1})", n=3)
msh(nd, "db.system.profile.find({ns: 'test.small'}, {_id: 0}).sort({ts: -1}).limit(1).toArray()[0]", n=40, label="db.system.profile.find({ns: 'test.small'}).sort({ts: -1}).limit(1)  // 级别 2 下 findOne 的一条记录")
msh(nd, "Object.keys(db.system.profile.find({ns: 'test.small'}).sort({ts: -1}).limit(1).toArray()[0]).join(', ')", n=6, label="Object.keys(<那条记录>).join(', ')")
msh(nd, "db.setProfilingLevel(0)", n=3)
print('== 四:system.profile 是 capped 集合(默认 1 MB);记录一多就会覆盖;大小可以改(先关再建)')
msh(nd, "db.system.profile.stats().capped + ' ' + db.system.profile.stats().maxSize", n=3, label="db.system.profile.stats().capped, maxSize")
msh(nd, "db.setProfilingLevel(0); db.system.profile.drop(); db.createCollection('system.profile', {capped: true, size: 4 * 1024 * 1024}); db.setProfilingLevel(2); db.system.profile.stats().maxSize", n=4)
msh(nd, "db.setProfilingLevel(0)", n=3)
print('== 五:profile 级别 2 对吞吐的影响:同样的 3,000 次 findOne,级别 0 / 1(阈值 100 ms,基本不记录)/ 2(全记录)各跑 5 次取中位数')
def run_find(): 
    for i in range(3000): c.test.small.find_one({'_id': 1})
res = {}
for lv in (0, 1, 2):
    c.test.command('profile', lv, slowms=100); res[lv] = bench(run_find, n=5)
c.test.command('profile', 0)
print(f'  级别 0:{fm(res[0])};级别 1:{fm(res[1])};级别 2:{fm(res[2])}(级别 2 是级别 0 的 {res[2] / res[0]:.2f} 倍)')
print('  级别 2 下一共执行了 (1 次预热 + 5 次) × 3,000 = 18,000 次 findOne')
msh(nd, "db.system.profile.countDocuments({})", n=3, label="db.system.profile.countDocuments({})  // 级别 2 跑完后,system.profile 是 4 MB 的 capped 集合")
print('== 六:sampleRate:slowms = 0 让每个操作都算“慢”,sampleRate = 0.1 只记录约 10%')
c.test.command('profile', 0, slowms=0, sampleRate=0.1)
msh(nd, "db.getProfilingStatus()", n=6)
n2 = len(slowlogs())
for i in range(1000): c.test.small.find_one({'_id': 1})
print(f'  slowms = 0、sampleRate = 0.1:1,000 次 findOne 后日志里新增 "Slow query" = {len(slowlogs()) - n2}')
nd.stop()
