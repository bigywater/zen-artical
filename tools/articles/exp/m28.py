import sys, os; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from ml import *
tee('m28'); reset()
n = Node('m28', cache=0.5); n.start(); c = n.client(); db = c.test
N = 150000
fill(db.big, N, lambda i: {'_id': i, 'k': (i * 7919) % 1000003, 'pad': 'x' * 1000})
fill(db.small, 50000, lambda i: {'_id': i, 'k': (i * 7919) % 1000003, 'pad': 'x' * 1000})
print(f'== 一:数据:big {N:,} 个文档(每个约 1 KB,共约 150 MB),small 50,000 个(约 50 MB),按没有索引的字段 k 排序。先看两个相关参数')
msh(n, 'db.adminCommand({getParameter: 1, allowDiskUseByDefault: 1, internalQueryMaxBlockingSortMemoryUsageBytes: 1})')
msh(n, 'db.big.stats().size / 1024 / 1024 + " MB(big 的 dataSize)"')
print('== 二:把 allowDiskUseByDefault 关掉(旧版本的默认行为):排序数据超过 100 MiB 的内存上限就报错')
msh(n, 'db.adminCommand({setParameter: 1, allowDiskUseByDefault: false})')
msh(n, 'try { db.big.find().sort({k: 1}).toArray().length } catch (e) { ({code: e.code, message: e.message.slice(0, 170)}) }', label='db.big.find().sort({k: 1})')
msh(n, 'db.small.find().sort({k: 1}).toArray().length', label='db.small.find().sort({k: 1})    // 50 MB,没超')
print('== 三:加 allowDiskUse: true 之后排序溢出到磁盘:explain 里 SORT 阶段 usedDisk 为 true')
msh(n, 'var e = db.big.find().sort({k: 1}).allowDiskUse().explain("executionStats"); var s = e.executionStats.executionStages; var out = []; while (s) { out.push({stage: s.stage, usedDisk: s.usedDisk, spills: s.spills, spilledBytes: s.spilledBytes, memLimit: s.memLimit}); s = s.inputStage }; ({nReturned: e.executionStats.nReturned, ms: e.executionStats.executionTimeMillis, stages: out.filter(x => x.stage.includes("SORT"))})', label='db.big.find().sort({k: 1}).allowDiskUse().explain("executionStats")', n=30)
def t_(fn, k=3): return bench(fn, k)
print('== 四:耗时:内存排序(small,50 MB)与溢出磁盘排序(big,150 MB),以及不排序直接读的耗时(各 3 次中位数)')
a = t_(lambda: list(db.small.find({}, {'pad': 0}).sort('k', 1).allow_disk_use(True))); b = t_(lambda: list(db.big.find({}, {'pad': 0}).sort('k', 1).allow_disk_use(True)))
a0 = t_(lambda: list(db.small.find({}, {'pad': 0}))); b0 = t_(lambda: list(db.big.find({}, {'pad': 0})))
print(f'  small(50,000 个):不排序 {fm(a0)};排序 {fm(a)}(内存)')
print(f'  big(150,000 个):  不排序 {fm(b0)};排序 {fm(b)}(溢出磁盘,约 150 MB 的排序数据)')
print('== 五:sort + limit:只保留前 N 个(top-k),不会超过内存上限,所以不需要 allowDiskUse')
msh(n, 'db.big.find({}, {pad: 0}).sort({k: 1}).limit(100).toArray().length', label='db.big.find().sort({k: 1}).limit(100)    // allowDiskUseByDefault 仍是 false')
msh(n, 'var e = db.big.find().sort({k: 1}).limit(100).explain("executionStats"); var s = e.executionStats.executionStages; var o = null; while (s) { if (s.stage.includes("SORT")) o = {stage: s.stage, usedDisk: s.usedDisk, limit: s.limitAmount}; s = s.inputStage }; o', n=20)
print('== 六:有索引时不排序:在 k 上建索引后,按 k 排序直接沿索引读,没有 SORT 阶段,也不受内存上限影响')
db.big.create_index('k')
msh(n, 'db.big.find({}, {pad: 0}).sort({k: 1}).toArray().length', label='db.big.find().sort({k: 1})    // 有索引,allowDiskUseByDefault 仍是 false')
msh(n, EXJS + 'ex(db.big.find().sort({k: 1}).explain("executionStats"))', label='explain', n=12)
c_ = t_(lambda: list(db.big.find({}, {'pad': 0}).sort('k', 1))); print(f'  有索引的排序读取全部 150,000 个文档(去掉 pad 字段):{fm(c_)}(无索引、溢出磁盘:{fm(b)})')
msh(n, 'db.adminCommand({setParameter: 1, allowDiskUseByDefault: true})')
n.stop()
