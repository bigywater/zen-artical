print('== 五:自定义 merge driver:.gitattributes 里 merge=<名字>,配置里 merge.<名字>.driver 是命令,%O %A %B 分别是基础、ours、theirs 的临时文件,%L 标记长度,%P 路径')
script('pick-max', f'echo "driver 被调用: base=$(cat $1) ours=$(cat $2) theirs=$(cat $3) 标记长度=$4 路径=$5" >> {LOGF}\no=$(sed "s/version=//" $2); t=$(sed "s/version=//" $3)\nif [ "$o" -ge "$t" ]; then cp $2 $2; else cp $3 $2; fi\nexit 0')
d3 = lab('l72c'); W(d3, {'.gitattributes': 'VERSION merge=maxver\n'}); R(d3, 'git config merge.maxver.driver "pick-max %O %A %B %L %P"')
