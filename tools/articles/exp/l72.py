tee('l72')
import ll as _ll
def run(d, cmd, t=0, **k): return _ll.run(d, cmd, t, **k)
def sh(d, cmd, t=0, **k): return _ll.sh(d, cmd, t, **k)
def ci(d, msg, files=None, t=0, **k): return _ll.ci(d, msg, files, t, **k)
BIN = LT / '_bin72'; shutil.rmtree(BIN, ignore_errors=True); BIN.mkdir(); LOGF = LT / 'filter72.log'
def script(name, body):
    f = BIN / name; f.write_text('#!/bin/sh\n' + body + '\n'); f.chmod(0o755)
def env(): return dict(PATH=f'{BIN}:/usr/bin:/bin:/usr/sbin:/sbin')
def R(d, cmd, t=0): return _ll.run(d, cmd, t, env=env())
def S(d, cmd, t=0, **k): return _ll.sh(d, cmd, t, env=env(), **k)
def clog(): return [l for l in LOGF.read_text().split('\n') if l] if LOGF.exists() else []
print('== 一:clean / smudge 过滤器:.gitattributes 把某类文件交给过滤器;add 时 clean 一遍再存进 blob,checkout 时 smudge 一遍再写到工作区')
script('redact-clean', f'echo "clean $1" >> {LOGF}; sed -E "s/^(password=).*/\\1<REDACTED>/"')
script('redact-smudge', f'echo "smudge $1" >> {LOGF}; cat')
d = lab('l72'); W(d, {'.gitattributes': '*.conf filter=redact\n'}); R(d, 'git config filter.redact.clean "redact-clean %f"; git config filter.redact.smudge "redact-smudge %f"')
W(d, {'app.conf': 'host=db.example.com\npassword=hunter2\nport=5432\n'}); LOGF.write_text('')
R(d, 'git add .gitattributes app.conf')
print('  git add 之后,暂存区里的 blob 内容:'); S(d, 'git cat-file -p :app.conf')
print('  工作区里的文件内容(没变):'); S(d, 'cat app.conf')
print('  过滤器被调用:', ' | '.join(clog()))
