import sys, os; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from ml import *
tee('m16'); reset()
n = Node('m16'); n.start(); c = n.client(); db = c.test
V = '{$jsonSchema: {bsonType: "object", required: ["name", "age"], properties: {name: {bsonType: "string", minLength: 2}, age: {bsonType: "int", minimum: 0, maximum: 150}}}}'
print('== 一:带 $jsonSchema 校验器的集合:合法文档插入成功,不合法文档报 121 Document failed validation,错误里带详细原因')
msh(n, f'db.createCollection("people", {{validator: {V}}})')
msh(n, 'db.people.insertOne({name: "Alice", age: 30})')
msh(n, 'try { db.people.insertOne({name: "B", age: 200, extra: 1}) } catch (e) { ({code: e.code, message: e.message, details: JSON.stringify(e.errInfo.details)}) }', n=60)
msh(n, 'try { db.people.insertOne({name: "Carol"}) } catch (e) { e.errInfo.details.schemaRulesNotSatisfied[0].missingProperties }')
msh(n, 'try { db.people.insertOne({name: "Dave", age: 30.5}) } catch (e) { JSON.stringify(e.errInfo.details.schemaRulesNotSatisfied[0].propertiesNotSatisfied[0]) }')
print('== 二:validationAction: "warn":不合法的文档照样写入,但 mongod 日志里记一条警告')
msh(n, 'db.runCommand({collMod: "people", validationAction: "warn"})')
msh(n, 'db.people.insertOne({name: "X", age: 999})')
lg = n.logs(r'Document would fail validation')
print(f'  mongod 日志里 "Document would fail validation" 的条数: {len(lg)}')
for j in lg[:1]: print('  日志:', json.dumps({k: j[k] for k in ('s', 'c', 'msg')}, ensure_ascii=False), '; attr 里的键:', sorted(j.get('attr', {}).keys()))
msh(n, 'db.people.countDocuments({})')
print('== 三:validationLevel:strict 校验所有插入和更新;moderate 对“已经不合法”的老文档不再校验更新')
db.legacy.insert_many([{'_id': 1, 'name': 'Ok', 'age': 20}, {'_id': 2, 'name': 'Bad', 'age': 'old'}])
msh(n, f'db.runCommand({{collMod: "legacy", validator: {V}, validationLevel: "strict", validationAction: "error"}})')
msh(n, 'db.legacy.find({$nor: [' + V + ']}).toArray().map(d => d._id)', label='db.legacy.find({$nor: [<同一个 $jsonSchema>]})    // 加校验器之前就存在的“不合法”文档不会被拒绝,但可以这样找出来')
for lvl in ('strict', 'moderate'):
    msh(n, f'db.runCommand({{collMod: "legacy", validationLevel: "{lvl}"}})')
    msh(n, 'try { db.legacy.updateOne({_id: 2}, {$set: {note: "x"}}).modifiedCount } catch (e) { e.message }', label='db.legacy.updateOne({_id: 2}, {$set: {note: "x"}})    // 老的不合法文档')
    msh(n, 'try { db.legacy.updateOne({_id: 1}, {$set: {age: "x"}}).modifiedCount } catch (e) { e.message }', label='db.legacy.updateOne({_id: 1}, {$set: {age: "x"}})    // 合法文档改成不合法')
print('== 四:validationLevel: "off" 和 bypassDocumentValidation')
msh(n, 'db.runCommand({collMod: "legacy", validationLevel: "strict"})')
msh(n, 'try { db.legacy.insertOne({_id: 3, name: "Zed", age: -5}) } catch (e) { e.message }')
msh(n, 'db.legacy.insertOne({_id: 3, name: "Zed", age: -5}, {bypassDocumentValidation: true}).acknowledged', label='db.legacy.insertOne({...不合法...}, {bypassDocumentValidation: true})')
msh(n, 'db.runCommand({collMod: "legacy", validationLevel: "off"})')
msh(n, 'db.legacy.insertOne({_id: 4, name: "Y", age: "?"}).acknowledged', label='db.legacy.insertOne({_id: 4, ...不合法...})    // validationLevel: off')
print('== 五:不只是 $jsonSchema:也可以用普通的查询表达式当校验器(比较字段之间的关系要用 $expr)')
msh(n, 'db.createCollection("events", {validator: {$expr: {$lte: ["$start", "$end"]}}})')
msh(n, 'db.events.insertOne({start: 1, end: 5}).acknowledged')
msh(n, 'try { db.events.insertOne({start: 9, end: 5}) } catch (e) { e.message + " / " + JSON.stringify(e.errInfo.details) }')
print('== 六:校验器存在哪里,以及 insertMany 的 ordered 与校验失败的关系')
msh(n, 'db.getCollectionInfos({name: "people"})[0].options')
msh(n, 'db.runCommand({collMod: "people", validationAction: "error"}); try { db.people.insertMany([{name: "Ann", age: 1}, {name: "?", age: 2}, {name: "Bob", age: 3}]) } catch (e) { ({inserted: e.result.insertedCount, writeErrors: e.writeErrors.length, errIndex: e.writeErrors[0].index}) }', label='db.people.insertMany([合法, 不合法, 合法])    // ordered 默认 true')
msh(n, 'db.people.countDocuments({name: {$in: ["Ann", "Bob"]}})')
msh(n, 'try { db.people.insertMany([{name: "Eve", age: 1}, {name: "?", age: 2}, {name: "Fay", age: 3}], {ordered: false}) } catch (e) { ({inserted: e.result.insertedCount, writeErrors: e.writeErrors.length}) }', label='db.people.insertMany([合法, 不合法, 合法], {ordered: false})')
n.stop()
