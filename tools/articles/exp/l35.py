import sys, os, re; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from ll import *
tee('l35')
SH = " | sed -E 's/[0-9a-f]{40}/<sha40>/g'"
def objs(d): return int(out1(d, "git count-objects -v | awk '/^count:|^in-pack:/{s+=$2} END{print s}'"))
def subj(d, rev): return out1(d, f'git log -1 --format=%s {rev}')
d = lab('l35'); base = ci(d, '起点', {'a.txt': 'a1\n', 'b.txt': 'b1\n'}, t=0)
W(d, {'a.txt': 'a1\na2 工作区改的\n', 'b.txt': 'b1\nb2 暂存的\n'}); run(d, 'git add b.txt'); W(d, {'b.txt': 'b1\nb2 暂存的\nb3 又改了没暂存\n'})
print('== 一:工作区状态:a.txt 只改了工作区,b.txt 一部分暂存、一部分没暂存')
sh(d, 'git status --short')
n0 = objs(d); run(d, 'git stash')
print('== 二:git stash 之后:refs/stash 是一个 commit,有 2 个 parent——基础提交和一个“index commit”')
sh(d, 'git status --short; echo "(工作区干净了)"; git stash list')
print(f'  对象数 {n0} → {objs(d)}(新增 {objs(d) - n0} 个:2 个 commit、2 个 tree、2 个 blob——工作区里的 a.txt 和 b.txt;暂存的 b.txt 在 git add 时就已经写入了)')
sh(d, 'git cat-file -p refs/stash' + SH)
W_ = out1(d, 'git rev-parse refs/stash'); P1, P2 = out1(d, 'git rev-parse refs/stash^1 refs/stash^2').split()
print(f'  ^1 是基础提交({P1 == base}),^2 的说明是: {subj(d, P2)!r}')
print('  三个 tree 各自装着什么:')
for nm, rev in [('基础 HEAD', 'HEAD'), ('^2(index commit,暂存区)', 'refs/stash^2'), ('refs/stash(工作区快照)', 'refs/stash')]:
    print(f'    {nm:<24} a.txt: {out1(d, f"git show {rev}:a.txt | tail -1")!r:<22} b.txt 末行: {out1(d, f"git show {rev}:b.txt | tail -1")!r}')
print('== 三:git stash show 就是 git diff 基础提交 ..stash 提交')
sh(d, 'git stash show -p | grep -E "^[+-][^+-]"')
print('  等价: git diff refs/stash^1 refs/stash → 完全相同:', out1(d, 'git stash show -p') == out1(d, 'git diff refs/stash^1 refs/stash'))
print('== 四:git stash -u 多一个 parent:装着未跟踪文件的 commit')
run(d, 'git stash drop -q')
W(d, {'a.txt': 'a1\n改了\n', 'new.txt': '未跟踪的新文件\n'}); run(d, 'git add a.txt')
sh(d, 'git stash -u; git cat-file -p refs/stash' + SH)
print(f'  ^3 的说明: {subj(d, "refs/stash^3")!r}'); sh(d, 'git ls-tree -r refs/stash^3 --name-only')
print('  对比:不加 -u 时 new.txt 不会进 stash(留在工作区):')
run(d, 'git stash drop -q'); W(d, {'a.txt': 'a1\n改了\n', 'new.txt': '未跟踪的新文件\n'}); run(d, 'git add a.txt'); sh(d, 'git stash -q; ls; git cat-file -p refs/stash | grep -c "^parent"')
run(d, 'git stash drop -q; rm -f new.txt; git checkout -q -- .')
print('== 五:stash 栈 = refs/stash 的 reflog:旧的 stash 没有任何 parent 链接,只是 reflog 里的记录')
run(d, 'git reset -q --hard'); 
for i in (1, 2, 3):
    W(d, {'a.txt': f'a1\n第 {i} 次\n'}); run(d, f'git stash push -q -m "第 {i} 个"')
sh(d, 'git stash list')
sh(d, "cat .git/logs/refs/stash | sed -E 's/^[0-9a-f]{40} [0-9a-f]{40} /<旧> <新> /; s/ [0-9]{10} [+-][0-9]{4}//'")
sh(d, 'git rev-parse stash@{0} stash@{1} | cut -c1-7 | tr "\\n" " "; echo; git rev-parse stash@{0}^ | cut -c1-7; echo "(stash@{0} 的 ^1 是基础提交,不是 stash@{1})"')
sh(d, 'git stash drop -q stash@{1}; git stash list; echo "(drop 的是 reflog 里的一行)"')
print('== 六:apply/pop 靠三方合并:基础 = stash 的 ^1,所以能应用到别的提交上;冲突时 pop 会保留这个 stash')
run(d, 'git stash clear')
W(d, {'a.txt': 'a1\nstash 里的改动\n'}); run(d, 'git stash -q')
ci(d, '之后又提交了别的', {'c.txt': 'c\n'}, t=5)
sh(d, 'git stash pop 2>&1 | head -3; git status --short; git stash list | wc -l')
run(d, 'git reset -q --hard; git stash clear')
W(d, {'a.txt': 'a1\nstash 里的改动\n'}); run(d, 'git stash -q'); ci(d, '同一处也被改了', {'a.txt': 'a1\n别人改的\n'}, t=6)
sh(d, 'git stash pop 2>&1 | grep -E "CONFLICT|kept|conflict" ; git status --short; git stash list | wc -l')
