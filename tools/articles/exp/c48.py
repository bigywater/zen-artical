print('  自定义网络 + --dns 1.1.1.1 --dns-search example.internal --dns-opt ndots:2:' + ex('bwlab-c48c', 'grep -v "^#" /etc/resolv.conf | grep -v "^$"').replace('\n', ' ; '))
