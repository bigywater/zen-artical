def ex(n, c): return dk('exec', n, 'sh', '-c', c)[1].strip()
print('== 一:容器里的 /etc/resolv.conf(Docker Engine 29.8.2)')
dk('network', 'create', '--label', 'bwlab=1', 'bwlab-c48net')
dk('run', '-d', '--name', 'bwlab-c48def', *LAB, 'alpine:3.20', 'sleep', '300')
dk('run', '-d', '--name', 'bwlab-c48a', *LAB, '--network', 'bwlab-c48net', '--network-alias', 'web', '--network-alias', 'frontend', 'alpine:3.20', 'sleep', '300')
dk('run', '-d', '--name', 'bwlab-c48b', *LAB, '--network', 'bwlab-c48net', 'alpine:3.20', 'sleep', '300')
print('  默认 bridge 上的容器:' + ex('bwlab-c48def', 'grep -v "^#" /etc/resolv.conf | grep -v "^$"').replace('\n', ' ; '))
print('  自定义网络上的容器:' + ex('bwlab-c48b', 'grep -v "^#" /etc/resolv.conf | grep -v "^$"').replace('\n', ' ; '))
print('== 二:解析容器名、网络别名、不存在的名字')
for name in ('bwlab-c48a', 'web', 'frontend', 'bwlab-c48b', 'nonexistent-name'):
    rc, o = dk('exec', 'bwlab-c48b', 'nslookup', name)
    ans = [l.split()[-1] for l in o.splitlines() if l.startswith('Address') and '#' not in l]
    print(f'  nslookup {name}:退出码 {rc};地址 {ans if ans else "无"}' + (f';{[l for l in o.splitlines() if "NXDOMAIN" in l or "can\'t" in l][:1]}' if rc else ''))
print(f'  容器 a 的真实 IP:{out("inspect", "--format", "{{range .NetworkSettings.Networks}}{{.IPAddress}}{{end}}", "bwlab-c48a")}')
print('  反向:别的容器在默认 bridge 上,能解析 bwlab-c48a 吗?' + ('能' if dk('exec', 'bwlab-c48def', 'nslookup', 'bwlab-c48a')[0] == 0 else '不能'))
print('== 三:127.0.0.11 在哪里监听')
print('  容器里监听的 UDP / TCP 端口:' + ex('bwlab-c48b', 'netstat -lnu 2>/dev/null | grep 127.0.0.11; netstat -lnt 2>/dev/null | grep 127.0.0.11').replace('\n', ' ; '))
print('  外部名字(github.com)解析:' + ex('bwlab-c48b', 'time -p nslookup github.com 2>&1 | grep -E "Address|real" | tr "\\n" " " | cut -c1-200'))
