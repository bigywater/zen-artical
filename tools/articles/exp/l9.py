import sys, os; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from ll import *
tee('l9')
d = lab('l9')
W(d, {'run.sh': '#!/bin/sh\necho hi\n', 'data.txt': 'x\n'})
(d / 'run.sh').chmod(0o755)
print('== 一:git 只看属主的可执行位:磁盘上各种权限提交进去后只有 100644 和 100755 两种')
for m in ['600', '611', '640', '644', '664', '700', '711', '744', '755', '775']:
    W(d, {f'p{m}': 'x\n'}); os.chmod(d / f'p{m}', int(m, 8))
sh(d, 'git add -A && git ls-files -s | awk \'{print $1, $4}\' | sort -k2')
sh(d, "stat -f '%Lp %N' p600 p611 p640 p664 p700 p711 p744 p775 | sort -k2")
print('== 二:clone 出去再检出,权限变成什么(受 umask 影响)')
shutil.rmtree(LT / 'l9clone', ignore_errors=True)
sh(d, 'git commit -q -m 第一次 && git clone -q . ../l9clone && cd ../l9clone && umask && stat -f "%Lp %N" p600 p611 p640 p664 p700 p711 p744 p775 p644 p755 | sort -k2')
print('== 三:chmod 之后 git 能看到变化,core.fileMode=true(默认):')
sh(d, 'chmod 755 data.txt; git status --short; git diff')
sh(d, 'git add data.txt; git ls-files -s data.txt; git commit -q -m 改权限; git log -1 --stat --format=%s')
print('== 四:core.fileMode=false:忽略磁盘上的权限变化(为不保留权限位的文件系统准备)')
sh(d, 'git config core.fileMode false; chmod 644 data.txt; git status --short; echo "[fileMode=false 下 chmod 644 后 status 为空]"; git ls-files -s data.txt')
sh(d, 'git config core.fileMode true; git status --short')
print('  git init 时会探测文件系统是否保存权限位:')
sh(LT, 'rm -rf l9probe && git init -q l9probe && git -C l9probe config core.fileMode')
print('== 五:fileMode=false 时,git 如何决定 add 新文件的模式、怎么手动改')
d2 = lab('l9b'); W(d2, {'tool.sh': '#!/bin/sh\n'}); (d2 / 'tool.sh').chmod(0o755)
sh(d2, 'git config core.fileMode false; git add tool.sh; git ls-files -s tool.sh')
sh(d2, 'git update-index --chmod=+x tool.sh; git ls-files -s tool.sh')
sh(d2, 'git update-index --chmod=-x tool.sh; git ls-files -s tool.sh')
sh(d2, 'git config core.fileMode true; git update-index --chmod=+x tool.sh; git ls-files -s tool.sh; git status --short')
print('== 六:fileMode=false 的另一面——已提交为 100755 的文件,在磁盘上被丢了权限也不会被发现')
d3 = lab('l9c'); W(d3, {'tool.sh': '#!/bin/sh\n'}); (d3 / 'tool.sh').chmod(0o755)
ci(d3, 'x', t=0)
sh(d3, 'chmod 644 tool.sh; git status --short; git config core.fileMode false; git status --short; echo "(fileMode=false 时 status 为空)"; git ls-files -s tool.sh')
sh(d3, 'git config core.fileMode true; git diff --summary')
