def mkimg(tag, seed, kb):
    d = ctx('c17_' + seed, {'Dockerfile': 'FROM alpine:3.20\nENV MODE=' + seed + '\nCMD ["cat","/f.bin"]\nCOPY f.bin /f.bin\n', 'f.bin': os.urandom(kb * 1024)})
    rc, o = build(d, tag, '--provenance=false', '--sbom=false'); assert rc == 0, o[-300:]
def sz(p): return os.path.getsize(p)
def kb(n): return f'{n / 1024:.0f} KB'
