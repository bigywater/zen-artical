import sys, time, random, os, json, subprocess, signal, statistics, threading, socket, select, re, collections, struct; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import rl
from rl import *
tee('r73'); R = {}
cl = Cluster(7370, 3, 1, name='c73'); time.sleep(1)
own = slot_owner_map(cl.nodes[0].c())
# 找:同属一个节点、槽位不同的两个 key;以及分属不同节点的 key
def pick():
    ks = [f'key{i}' for i in range(200)]
    a = ks[0]
    same = next(k for k in ks[1:] if own[keyslot(k)] == own[keyslot(a)] and keyslot(k) != keyslot(a))
    diff = next(k for k in ks[1:] if own[keyslot(k)] != own[keyslot(a)])
    return a, same, diff
a, same, diff = pick()
node = C(own[keyslot(a)])
print(f'key a="{a}":槽 {keyslot(a)},节点 {own[keyslot(a)]}')
print(f'key same="{same}":槽 {keyslot(same)},节点 {own[keyslot(same)]}(和 a 同一个节点,但槽不同)')
print(f'key diff="{diff}":槽 {keyslot(diff)},节点 {own[keyslot(diff)]}(另一个节点)')
print()
print('== 一:多 key 命令:即使两个 key 在同一个节点上,只要槽不同就是 CROSSSLOT')
sh(node, 'MSET', a, 1, same, 2)
tn = C(own[keyslot('t')]); sh(tn, 'MSET', '{t}1', 1, '{t}2', 2)
sh(tn, 'MGET', '{t}1', '{t}2')
print()
print('== 二:换几个多 key 命令')
sn = C(own[keyslot('x{s}')])
sh(node, 'DEL', a, same)
sh(node, 'MGET', a, same)
sh(node, 'RENAME', a, same)
sh(node, 'SUNION', a, same)
sh(node, 'SADD', a, 1)
sh(node, 'SINTERSTORE', same, a, '{q}1')
print()
print('== 三:同一个 key 在集合运算里出现多次,不算跨槽;单个 key 的命令永远不会 CROSSSLOT')
sh(node, 'SUNION', a, a)
sh(node, 'SCARD', a)
print()
print('== 四:事务 MULTI/EXEC 里的多个 key')
sh(node, 'MULTI'); sh(node, 'SET', a, 1); sh(node, 'SET', same, 2); sh(node, 'EXEC')
print('(改成同一个槽:)')
tn2 = C(own[keyslot('t')]); sh(tn2, 'MULTI'); sh(tn2, 'SET', '{t}a', 1); sh(tn2, 'SET', '{t}b', 2); sh(tn2, 'EXEC')
print()
print('== 五:Lua 脚本')
sh(node, 'EVAL', "return redis.call('SET', KEYS[1], 1) and redis.call('SET', KEYS[2], 2)", 2, a, same)
sh(node, 'EVAL', "return redis.call('SET', KEYS[1], 1) and redis.call('SET', 'undeclared', 2)", 1, a)
print(f'(下面这条:没有在 KEYS 里声明的 {same},它和 {a} 在同一个节点、不同槽)')
sh(node, 'EVAL', "redis.call('DEL', KEYS[1]); return redis.call('SET', ARGV[1], 2)", 1, a, same)
sh(tn2, 'EVAL', "redis.call('SET', KEYS[1], 1); redis.call('SET', KEYS[2], 2); return 'ok'", 2, '{t}x', '{t}y')
print()
print('== 六:流水线里的多条单 key 命令不受影响(每条命令只涉及一个槽)')
r = node.pipeline([['SET', a, 1], ['GET', a], ['INCR', a]]); print(r)
print()
print('== 七:分属不同节点的 key,发多 key 命令')
sh(node, 'MSET', a, 1, diff, 2)
save('r73', R); cl.cleanup()
