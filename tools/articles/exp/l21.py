import sys, os, hashlib; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from ll import *
tee('l21')
DAY = 86400
def objpath(d, sha): return d / '.git' / 'objects' / sha[:2] / sha[2:]
def age(d, sha, days):
    t = time.time() - days * DAY; os.utime(objpath(d, sha), (t, t))
def exists(d, sha): return run(d, f'git cat-file -e {sha}')[0] == 0
def blob(d, text): return out1(d, f'printf %s {shq(text)} | git hash-object -w --stdin')
d = lab('l21'); ci(d, '第一次', {'a.txt': '1\n'}, t=0)
print('== 一:造不可达对象:提交一个 commit 再 reset 掉,并清空 reflog')
c2 = ci(d, '会被丢掉的提交', {'a.txt': '2\n'}, t=1)
sh(d, 'git reset -q --hard HEAD~1; git reflog expire --expire=now --all; git log --oneline')
sh(d, 'git fsck --unreachable --no-reflogs 2>&1 | sed "s/ [0-9a-f]\\{40\\}/ <sha>/"')
sh(d, 'git prune -n | sed "s/^[0-9a-f]\\{40\\}/<sha>/"')
print(f'  不可达的提交 {c2[:10]}… 此刻是否存在: {exists(d, c2)}')
print('== 二:宽限期:两个不可达的 blob,一个“13 天前”写入,一个“15 天前”写入(用 touch 改文件时间)')
A = blob(d, '13 天前的 blob\n'); B = blob(d, '15 天前的 blob\n'); age(d, A, 13); age(d, B, 15)
for nm, sha in [('A(13 天前)', A), ('B(15 天前)', B)]: print(f'  {nm}: {sha[:10]}…  mtime 距今 {(time.time() - objpath(d, sha).stat().st_mtime) / DAY:.1f} 天')
sh(d, 'git prune --expire=2.weeks.ago -n -v | sed "s/^[0-9a-f]\\{40\\}/<sha>/"')
print('  对照:不带过期时间的 git prune -n 会列出所有不可达对象(包括当前的提交 c2 及它的 tree、blob):')
sh(d, 'git prune -n | wc -l')
sh(d, 'git gc -q')
print(f'  git gc 之后(默认 gc.pruneExpire):A 存在 {exists(d, A)},B 存在 {exists(d, B)},c2 存在 {exists(d, c2)}')
print('== 三:刚写入的对象没有宽限期时会被立刻删;暂存区里的对象不会')
N1 = blob(d, '刚写入、没有任何引用的 blob\n')
W(d, {'staged.txt': '暂存区里的内容\n'}); run(d, 'git add staged.txt'); S1 = out1(d, 'git rev-parse :staged.txt')
sh(d, 'git prune --expire=now -v | sed "s/^[0-9a-f]\\{40\\}/<sha>/"')
print(f'  git prune --expire=now 之后:刚写入的 blob 存在 {exists(d, N1)};暂存区的 blob 存在 {exists(d, S1)}')
print('== 四:reflog 保护着“看起来丢掉了”的提交:reset --hard 之后 gc --prune=now 也删不掉它(这一节的提交用真实时间,reflog 条目才是“新的”)')
d2 = lab('l21b'); ci(d2, '第一次', {'a.txt': '1\n'}, t='now'); c = ci(d2, '第二次', {'a.txt': '2\n'}, t='now')
sh(d2, 'git reset -q --hard HEAD~1; git reflog | cat | sed -E "s/^([0-9a-f]{7}) /<sha> /"', t='now')
sh(d2, 'git gc -q --prune=now')
print(f'  gc --prune=now 之后,被 reset 丢掉的提交存在: {exists(d2, c)}(reflog 还引用着它)')
sh(d2, 'git reflog expire --expire=now --expire-unreachable=now --all; git gc -q --prune=now')
print(f'  清空 reflog 再 gc --prune=now 之后,这个提交存在: {exists(d2, c)}')
print('== 五:不可达的对象在 pack 里:gc 把它们放进 cruft pack,过期后才真正删除')
d3 = lab('l21c'); ci(d3, '第一次', {'a.txt': '1\n'}, t=0); c = ci(d3, '第二次', {'a.txt': '2\n'}, t=1)
run(d3, 'git repack -adq'); sh(d3, 'git reset -q --hard HEAD~1; git reflog expire --expire=now --all')
sh(d3, 'git gc -q; ls .git/objects/pack | sed -E "s/pack-[0-9a-f]{40}/pack-<hash>/"')
print(f'  gc 之后(默认过期 2 周):不可达的提交存在 {exists(d3, c)}')
mt = next((d3 / '.git' / 'objects' / 'pack').glob('*.mtimes'), None)
print(f'  cruft pack 的 .mtimes 文件: {"有" if mt else "没有"}')
sh(d3, 'git gc -q --prune=now; ls .git/objects/pack | sed -E "s/pack-[0-9a-f]{40}/pack-<hash>/"')
print(f'  gc --prune=now 之后:不可达的提交存在 {exists(d3, c)}')
