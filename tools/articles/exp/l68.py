import sys, os, re; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from ll import *
tee('l68')
import ll as _ll
def run(d, cmd, t='now', **k): return _ll.run(d, cmd, t, **k)
def sh(d, cmd, t='now', **k): return _ll.sh(d, cmd, t, **k)
def ci(d, msg, files=None, t='now', **k): return _ll.ci(d, msg, files, t, **k)
K = LT / '_ssh'; K.mkdir(exist_ok=True)
for nm in ('alice', 'mallory'):
    if not (K / nm).exists(): subprocess.run(['ssh-keygen', '-q', '-t', 'ed25519', '-N', '', '-C', f'{nm}@example.com', '-f', str(K / nm)], check=True)
def fp(nm): return subprocess.run(['ssh-keygen', '-lf', str(K / f'{nm}.pub')], capture_output=True, text=True).stdout.split()[1]
pub = lambda nm: (K / f'{nm}.pub').read_text().strip()
ALLOWED = K / 'allowed_signers'; ALLOWED.write_text(f'alice@example.com {pub("alice")}\n')
d = lab('l68')
run(d, f'git config gpg.format ssh; git config user.signingkey {K / "alice.pub"}')
print('== 一:用 SSH 密钥签名提交:gpg.format=ssh、user.signingkey=<公钥文件>,git commit -S')
sh(d, 'git config --get-regexp "gpg|signing" | sed -E "s#/[^ ]*/_ssh#<ssh目录>#"')
W(d, {'a': '1\n'}); run(d, 'git add a'); c1 = ci(d, '签名的提交', None, t=0, extra='-S')
rc, o = run(d, 'git cat-file -p HEAD | sed -n "1,12p"')
for l in o.split('\n'): print('  | ' + re.sub(r'([0-9a-f]{40})', '<sha40>', l)[:100])
print(f'  (gpgsig 头:从 -----BEGIN SSH SIGNATURE----- 到 -----END SSH SIGNATURE-----,后续行以空格开头)')
print('== 二:验证:没有 allowedSignersFile 时 git 不知道该信任谁')
sh(d, 'git log -1 --show-signature --format=%s 2>&1 | head -4 | sed -E "s/SHA256:[A-Za-z0-9+\\/]+/SHA256:<指纹>/"')
run(d, f'git config gpg.ssh.allowedSignersFile {ALLOWED}')
print('  配置 gpg.ssh.allowedSignersFile 之后(文件内容:一行“主体 公钥类型 公钥”):')
sh(d, 'git log -1 --show-signature --format=%s 2>&1 | head -4 | sed -E "s/SHA256:[A-Za-z0-9+\\/]+/SHA256:<指纹>/"')
print(f'  签名里的指纹与 ssh-keygen -l 给出的 alice 公钥指纹一致: {fp("alice") in out1(d, "git log -1 --show-signature --format=%s 2>&1")}')
print('== 三:手工验证:取出 commit 对象,去掉 gpgsig 头,剩下的就是被签名的内容;用 ssh-keygen -Y verify(命名空间 git)')
raw = subprocess.run([GIT, 'cat-file', 'commit', 'HEAD'], cwd=d, env=lenv(), capture_output=True).stdout.decode()
lines = raw.split('\n'); sig = []; payload = []; ins = False
for l in lines:
    if l.startswith('gpgsig '): ins = True; sig.append(l[7:]); continue
    if ins and l.startswith(' '): sig.append(l[1:]); continue
    ins = False; payload.append(l)
(K / 'payload').write_text('\n'.join(payload)); (K / 'sig').write_text('\n'.join(sig) + '\n')
r = subprocess.run(f'ssh-keygen -Y verify -f {ALLOWED} -I alice@example.com -n git -s {K / "sig"} < {K / "payload"}', shell=True, capture_output=True, text=True)
print('  ssh-keygen -Y verify:', re.sub(r'SHA256:[A-Za-z0-9+/]+', 'SHA256:<指纹>', r.stdout.strip()), '| 退出码', r.returncode)
(K / 'payload2').write_text('\n'.join(payload).replace('签名的提交', '被篡改的提交'))
r = subprocess.run(f'ssh-keygen -Y verify -f {ALLOWED} -I alice@example.com -n git -s {K / "sig"} < {K / "payload2"}', shell=True, capture_output=True, text=True)
print('  改一个字之后再验证:', re.sub(r'SHA256:[A-Za-z0-9+/]+', 'SHA256:<指纹>', (r.stdout + r.stderr).strip())[:100], '| 退出码', r.returncode)
r = subprocess.run(f'ssh-keygen -Y verify -f {ALLOWED} -I alice@example.com -n other -s {K / "sig"} < {K / "payload"}', shell=True, capture_output=True, text=True)
print('  命名空间不是 git(-n other):', (r.stdout + r.stderr).strip()[:100], '| 退出码', r.returncode)
print('== 四:篡改提交:把说明改一个字、保留原来的 gpgsig,写成新的 commit 对象')
tampered = raw.replace('签名的提交', '被篡改的提交')
th = subprocess.run([GIT, 'hash-object', '-t', 'commit', '-w', '--stdin'], cwd=d, env=lenv(), input=tampered.encode(), capture_output=True).stdout.decode().strip()
rc_, o_ = run(d, f'git verify-commit {th} 2>&1'); print('  $ git verify-commit <篡改后的提交>'); [print('    ' + l) for l in o_.split('\n') if l]; print(f'  退出码 {rc_}')
print('== 五:用别人的密钥签名:不在 allowed_signers 里的签名者')
run(d, f'git config user.signingkey {K / "mallory.pub"}'); W(d, {'a': '2\n'}); run(d, 'git add a'); c2 = ci(d, '陌生人签名的提交', None, t=1, extra='-S')
sh(d, 'git log -1 --show-signature --format=%s 2>&1 | head -4 | sed -E "s/SHA256:[A-Za-z0-9+\\/]+/SHA256:<指纹>/"')
ALLOWED2 = K / 'allowed_signers_expired'; ALLOWED2.write_text(f'alice@example.com valid-before="20200101" {pub("alice")}\n')
run(d, f'git config user.signingkey {K / "alice.pub"}'); W(d, {'a': '3\n'}); run(d, 'git add a'); ci(d, 'alice 再签一次', None, t=2, extra='-S')
run(d, f'git config gpg.ssh.allowedSignersFile {ALLOWED2}')
sh(d, 'git log -1 --show-signature --format=%s 2>&1 | head -4 | sed -E "s/SHA256:[A-Za-z0-9+\\/]+/SHA256:<指纹>/"')
run(d, f'git config gpg.ssh.allowedSignersFile {ALLOWED}')
print('== 六:%G? 状态码:G 好签名、B 坏签名、U 好签名但未受信、N 没有签名、E 无法检查;以及签名的标签')
ci(d, '没签名的提交', {'b': '1\n'}, t=3)
sh(d, "git log --format='%G? %GS  %s' | sed -E 's/^(.) /\\1  /'")
run(d, 'git tag -s -m "签名标签" v1', 4); sh(d, 'git tag -v v1 2>&1 | head -3 | sed -E "s/SHA256:[A-Za-z0-9+\\/]+/SHA256:<指纹>/"; git cat-file -p v1 | grep -c "BEGIN SSH SIGNATURE" | sed "s/^ */标签对象里的签名块个数: /"')
