import sys, os, re; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from ll import *
tee('l66')
import ll as _ll
def run(d, cmd, t='now', **k): return _ll.run(d, cmd, t, **k)
def sh(d, cmd, t='now', **k): return _ll.sh(d, cmd, t, **k)
def ci(d, msg, files=None, t='now', **k): return _ll.ci(d, msg, files, t, **k)
SAN = "sed -E 's/[0-9a-f]{40}/<sha40>/g; s/\\b[0-9a-f]{7}\\b/<sha7>/g'"
d = lab('l66'); c1 = ci(d, '提交一', {'a': '1\n'}, t=0); c2 = ci(d, '提交二', {'a': '2\n'}, t=1)
print('== 一:给提交 2 加一条笔记:提交本身的 hash 不变,笔记存在另一个 ref(refs/notes/commits)里')
h0 = out1(d, 'git rev-parse HEAD'); sh(d, 'git notes add -m "这次提交通过了人工评审,评审人:小王" HEAD')
print(f'  HEAD 的 hash 没变: {out1(d, "git rev-parse HEAD") == h0}')
sh(d, "git log -2 --format='%h %s%n%N' | sed -E 's/^[0-9a-f]{7} /<sha7> /' ")
sh(d, "git for-each-ref --format='%(refname)' refs/notes; git notes list | " + SAN)
print('== 二:refs/notes/commits 是一个普通的分支:它的 tree 里“文件名=被注解的提交 hash,内容=笔记”')
sh(d, 'git cat-file -p refs/notes/commits^{tree} | ' + SAN + '; echo "--- 文件名就是被注解的提交的完整 hash;内容:"; git cat-file -p refs/notes/commits:$(git rev-parse HEAD)')
print(f'  文件名等于 HEAD 的完整 hash: {out1(d, "git ls-tree --name-only refs/notes/commits") == h0}')
sh(d, 'git log --format="%s" refs/notes/commits')
print('  再改一次(append / 编辑)就是在这个“分支”上再加一个提交:')
sh(d, 'git notes append -m "补充:已合并到主线" HEAD; git log --format="%s" refs/notes/commits | tr "\\n" "|"; echo; git notes show HEAD')
print('== 三:可以有多个命名空间(--ref),并配置 log 显示哪些')
sh(d, 'git notes --ref=build add -m "构建 #1234 成功" HEAD; git for-each-ref --format="%(refname)" refs/notes | tr "\\n" " "; echo')
sh(d, "git log -1 --format='%s%n%N' | head -4; echo '--- 加上 --notes=build:'; git log -1 --notes=build --format='%s' ; git log -1 --notes=build | tail -3")
sh(d, 'git config notes.displayRef "refs/notes/*"; echo "--- 设置 notes.displayRef=refs/notes/* 之后:"; git log -1 | tail -5')
print('== 四:rebase / amend 之后笔记就“丢”了:笔记按旧 hash 挂着;配置 notes.rewriteRef 才会随改写复制过去')
d2 = lab('l66b'); ci(d2, 'B1', {'a': '1\n'}, t=0); run(d2, 'git checkout -q -b topic'); ci(d2, 'T1', {'t': '1\n'}, t=1); run(d2, 'git notes add -m "T1 的笔记" HEAD'); run(d2, 'git checkout -q main'); ci(d2, 'B2', {'b': '1\n'}, t=2); run(d2, 'git checkout -q topic')
run(d2, 'git rebase -q main', 10)
sh(d2, 'git log -1 --format="%s  笔记: [%N]" ')
print(f'  笔记仍然挂在旧提交上: {out1(d2, "git notes list | wc -l").strip()} 条笔记,对应的提交现在已不在 topic 分支上')
d3 = lab('l66c'); ci(d3, 'B1', {'a': '1\n'}, t=0); run(d3, 'git config notes.rewriteRef refs/notes/commits'); run(d3, 'git checkout -q -b topic'); ci(d3, 'T1', {'t': '1\n'}, t=1); run(d3, 'git notes add -m "T1 的笔记" HEAD'); run(d3, 'git checkout -q main'); ci(d3, 'B2', {'b': '1\n'}, t=2); run(d3, 'git checkout -q topic'); run(d3, 'git rebase -q main', 10)
sh(d3, 'git log -1 --format="%s  笔记: [%N]"; git notes list | wc -l | sed "s/^ */现在 notes 里的条数: /"')
print('== 五:笔记很多时,tree 会用目录“扇出”(fanout),和 .git/objects 的做法一样')
t0 = int(BASE_T.timestamp())
for step_n in (10, 50, 100, 150, 200, 300):
    d4 = lab('l66d')
    stream = [f'commit refs/heads/main\ncommitter A <a@e> {t0 + i} +0000\ndata 2\nx\nM 100644 inline f.txt\ndata {len(str(i)) + 1}\n{i}\n\n' for i in range(1, step_n + 1)]
    subprocess.run([GIT, 'fast-import', '--quiet'], cwd=d4, env=lenv(), input=''.join(stream).encode(), check=True)
    run(d4, "git rev-list main | while read c; do git notes add -f -m note $c; done")
    top = out1(d4, 'git ls-tree --name-only refs/notes/commits').split('\n'); n_notes = int(out1(d4, 'git notes list | wc -l').strip())
    kinds = 'hash 作文件名' if all(len(x) == 40 for x in top) else ('两位十六进制的目录(扇出)' if all(len(x) == 2 for x in top) else '混合')
    print(f'  {n_notes:>4} 条笔记:顶层 tree 有 {len(top):>3} 个条目,类型:{kinds};第一个条目:{top[0][:12]}')
print('== 六:笔记默认不随 push / fetch 同步,clone 也拿不到:要显式指定 refspec')
R = LT / 'l66remote.git'; shutil.rmtree(R, ignore_errors=True); run(d, f'git clone -q --bare . {R}')
run(d, f'git push -q {R} main'); sh(d, f'git ls-remote {R} | sed -E "s/^[0-9a-f]{{40}}/<sha40>/"')
c = LT / 'l66cl'; shutil.rmtree(c, ignore_errors=True); run(LT, f'git clone -q {R} l66cl'); sh(c, 'git notes list | wc -l | sed "s/^ */clone 之后本地的笔记数: /"')
run(d, f'git push -q {R} "refs/notes/*:refs/notes/*"'); sh(c, 'git fetch -q origin "refs/notes/*:refs/notes/*"; git notes list | wc -l | sed "s#^ *#显式 fetch 之后本地的笔记数: #"; git log -1 --format="%s: %N" | head -2')
