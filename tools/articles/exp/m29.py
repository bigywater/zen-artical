import sys, os; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from ml import *
tee('m29'); reset()
n = Node('m29'); n.start(); c = n.client(); db = c.test
N = 200000
fill(db.t, N, lambda i: {'_id': i, 'a': i % 1000, 'b': (i * 7) % 5000, 'c': i % 50, 'd': (i * 31) % 100000})
db.t.create_index('a'); db.t.create_index('b'); db.t.create_index('c')
print('== 一:$or 的每个分支都有索引时,每个分支各走自己的索引(OR 阶段合并去重)')
msh(n, EXJS + 'ex(db.t.find({$or: [{a: 5}, {b: 17}]}).explain("executionStats"))', n=12, label='db.t.find({$or: [{a: 5}, {b: 17}]})')
print('== 二:只要有一个分支没有可用索引,整个 $or 退化成全表扫描')
msh(n, EXJS + 'ex(db.t.find({$or: [{a: 5}, {d: 17}]}).explain("executionStats"))', n=12, label='db.t.find({$or: [{a: 5}, {d: 17}]})    // d 没有索引')
print('== 三:$or 之外还有别的条件:外层条件 {c: 7} 可以走自己的索引,也可以和 $or 一起分配')
msh(n, EXJS + 'ex(db.t.find({c: 7, $or: [{a: 5}, {b: 17}]}).explain("executionStats"))', n=12, label='db.t.find({c: 7, $or: [{a: 5}, {b: 17}]})')
db.t.create_index([('c', 1), ('a', 1)]); db.t.create_index([('c', 1), ('b', 1)])
msh(n, EXJS + 'ex(db.t.find({c: 7, $or: [{a: 5}, {b: 17}]}).explain("executionStats"))', n=12, label='建了 {c, a} 和 {c, b} 两个复合索引之后,同一个查询')
print('== 四:$or + sort:每个分支按排序字段的顺序读出再合并(SORT_MERGE),要求每个分支的索引都能提供这个顺序')
db.t.create_index([('a', 1), ('d', 1)]); db.t.create_index([('b', 1), ('d', 1)])
msh(n, EXJS + 'ex(db.t.find({$or: [{a: 5}, {b: 17}]}).sort({d: 1}).explain("executionStats"))', n=12, label='db.t.find({$or: [{a: 5}, {b: 17}]}).sort({d: 1})    // 有 {a, d} 和 {b, d}')
db.t.drop_index('b_1_d_1')
msh(n, EXJS + 'ex(db.t.find({$or: [{a: 5}, {b: 17}]}).sort({d: 1}).explain("executionStats"))', n=12, label='删掉 {b, d} 索引后同一个查询')
print('== 五:$or 的两个分支命中同一个文档时只返回一次(去重),代价是检查的键数是两边之和。用 {a: 5} 和 {b: 35}:b = 35 的文档同时也满足 a = 5')
msh(n, 'db.t.countDocuments({a: 5}) + " + " + db.t.countDocuments({b: 35}) + " (两个分支各自的命中数);并集 " + db.t.countDocuments({$or: [{a: 5}, {b: 35}]}) + ";同时满足两个分支的 " + db.t.countDocuments({a: 5, b: 35})', note='分支命中数、并集、交集')
msh(n, EXJS + 'ex(db.t.find({$or: [{a: 5}, {b: 35}]}).explain("executionStats"))', n=12, label='db.t.find({$or: [{a: 5}, {b: 35}]})')
msh(n, EXJS + 'ex(db.t.find({$or: [{a: 5}, {a: 5, b: 3}]}).explain("executionStats"))', n=12, label='db.t.find({$or: [{a: 5}, {a: 5, b: 3}]})    // 第二个分支被第一个包含,优化器直接化简')
print('== 六:用 $in 替代同一字段上的 $or;以及 $or 与 $in 的耗时对比(9 次中位数)')
msh(n, EXJS + 'ex(db.t.find({$or: [{a: 5}, {a: 6}, {a: 7}]}).explain("executionStats"))', n=12, label='db.t.find({$or: [{a: 5}, {a: 6}, {a: 7}]})')
msh(n, EXJS + 'ex(db.t.find({a: {$in: [5, 6, 7]}}).explain("executionStats"))', n=12, label='db.t.find({a: {$in: [5, 6, 7]}})')
t_or = bench(lambda: list(db.t.find({'$or': [{'a': 5}, {'a': 6}, {'a': 7}]})), 9); t_in = bench(lambda: list(db.t.find({'a': {'$in': [5, 6, 7]}})), 9)
t_or2 = bench(lambda: list(db.t.find({'$or': [{'a': 5}, {'b': 17}]})), 9); t_two = bench(lambda: (list(db.t.find({'a': 5})), list(db.t.find({'b': 17}))), 9)
print(f'  同一字段:$or 三个分支 {fm(t_or)};$in {fm(t_in)}')
print(f'  不同字段:一条 $or 查询 {fm(t_or2)};应用端拆成两条查询再合并 {fm(t_two)}')
n.stop()
