def build(name, ntrack, nuntrack):
    d = lab(name); rnd = random.Random(33)
    W(d, {f'src/d{i // 500:03d}/f{i:06d}.txt': f'内容 {i} ' + 'x' * rnd.randint(50, 200) + '\n' for i in range(ntrack)}); run(d, 'git add -A && git commit -q -m x', 0)
    W(d, {f'build/o{i // 100:03d}/u{i:06d}.o': 'obj\n' for i in range(nuntrack)})
    time.sleep(1.1); run(d, 'git status --short'); time.sleep(1.1); run(d, 'git status --short'); return d
def tm(d, cmd='git status --short', n=5):
    ts = []
    for _ in range(n):
        t0 = time.perf_counter(); run(d, cmd); ts.append((time.perf_counter() - t0) * 1000)
    return median(ts)
def lstat(d): return out1(d, "GIT_TRACE2_PERF=1 git status --short 2>&1 | grep -E 'sum_lstat' | sed -E 's/.*sum_lstat:([0-9]+).*/\\1/' | paste -sd+ - | bc")
def settle(d): time.sleep(1.1); run(d, 'git status --short'); time.sleep(1.1); run(d, 'git status --short')
print('== 一:基线(1 万个已跟踪文件 + 3,000 个未跟踪的 .o):git status 要对每个已跟踪文件 lstat 一次')
d = build('l33a', 10000, 3000)
sh(d, 'git status --short; git ls-files | wc -l; find build -type f | wc -l')
t0 = tm(d); print(f'  git status 耗时(5 次中位数): {t0:.1f} ms;lstat 次数(preload 与 refresh 之和): {lstat(d)}')
print('== 二:在 1 万个文件的仓库上打开 untracked cache 与 fsmonitor:lstat 次数变了,耗时几乎没变')
sh(d, 'git update-index --test-untracked-cache 2>&1 | tail -1; git config core.untrackedCache true; git status --short')
print('  index 里的扩展块:', [x[0] for x in parse_index(d / '.git' / 'index')[2]]); settle(d)
t1 = tm(d); print(f'  + untracked cache: {t1:.1f} ms;lstat 次数 {lstat(d)}')
sh(d, 'git config core.fsmonitor true; git status --short; sleep 1; git fsmonitor--daemon status 2>&1 | sed -E "s#\'.*\'#\'<repo>\'#"')
print('  index 里的扩展块:', [x[0] for x in parse_index(d / '.git' / 'index')[2]]); settle(d)
t2 = tm(d); print(f'  + fsmonitor: {t2:.1f} ms;lstat 次数 {lstat(d)}')
run(d, 'git fsmonitor--daemon stop')
print('  (1 万个文件时 lstat 本来就很快:git 用 preload-index 多线程并行 lstat,1 万次只要约 9 毫秒)')
print('== 三:放大到 10 万个已跟踪文件 + 2 万个未跟踪文件')
d = build('l33b', 100000, 20000)
sh(d, 'git ls-files | wc -l; find build -type f | wc -l')
tb = tm(d); lb = lstat(d); print(f'  基线 git status: {tb:.1f} ms;lstat 次数 {lb}')
run(d, 'git config core.untrackedCache true; git status --short'); settle(d)
tu = tm(d); print(f'  + untracked cache: {tu:.1f} ms')
run(d, 'git config core.fsmonitor true; git status --short'); time.sleep(2); settle(d)
tf = tm(d); lf = lstat(d); print(f'  + fsmonitor(两个都开): {tf:.1f} ms;lstat 次数 {lf}')
run(d, 'git config --unset core.untrackedCache; git update-index --no-untracked-cache'); settle(d)
tf2 = tm(d); print(f'  只开 fsmonitor(关掉 untracked cache): {tf2:.1f} ms')
