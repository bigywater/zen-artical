print('== 五:代价:一个常驻进程,每个仓库一个;要手工停,配置里关掉 fsmonitor 之后不会自动退出')
sh(d, 'git fsmonitor--daemon status 2>&1 | sed -E "s#\'.*\'#\'<repo>\'#"; ls .git | grep fsmonitor | tr "\n" " "; echo')
