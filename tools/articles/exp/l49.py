import sys, os; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from ll import *
tee('l49')
def mk(name):
    d = lab(name); ci(d, 'M1 基础', {'base.txt': 'base\n'}, t=0)
    run(d, 'git checkout -q -b feature', 1); ci(d, 'F1 功能的第一步', {'f1.txt': 'f1\n'}, t=2); ci(d, 'F2 功能的第二步', {'f2.txt': 'f2\n'}, t=3)
    run(d, 'git checkout -q main', 4); ci(d, 'M2 主线上的提交', {'m2.txt': 'm2\n'}, t=5)
    run(d, 'git merge -q --no-ff -m "合并 feature(M)" feature', 6); ci(d, 'M3 合并之后的提交', {'m3.txt': 'm3\n'}, t=7); return d
def files(d): return out1(d, 'git ls-files').replace('\n', ' ')
print('== 一:合并提交 M 有两个 parent:^1 是合并时你所在的 main,^2 是被合并进来的 feature')
d = mk('l49a')
sh(d, "git log --graph --format='%s' | sed -E 's/^/  /'")
sh(d, "echo \"M^1 = $(git log -1 --format=%s HEAD~1^1)\"; echo \"M^2 = $(git log -1 --format=%s HEAD~1^2)\"")
print(f'  当前文件: {files(d)}')
print('== 二:git revert M 直接报错:不知道要撤销“相对哪个 parent 的差异”')
sh(d, 'git revert --no-edit HEAD~1 2>&1 | head -3')
print('== 三:-m 1:以 main 一侧(^1)为主线,撤销的是“feature 带进来的东西”')
d = mk('l49b'); run(d, 'git revert --no-edit -m 1 HEAD~1', t=20)
print(f'  文件: {files(d)}   (f1.txt、f2.txt 没了;m2.txt、m3.txt 还在)')
sh(d, 'git log -1 --format=%B | head -3')
print(f'  把现在的 HEAD 和 M 的 ^1(M2)比较,差异文件只有: {out1(d, "git diff --name-only HEAD~2^1 HEAD").replace(chr(10), " ")}(M3 在 M 之后的改动保留了,f1、f2 的改动被撤销)')
print('== 四:-m 2:以 feature 一侧(^2)为主线,撤销的是“main 带进来的东西”——通常不是你想要的')
d = mk('l49c'); run(d, 'git revert --no-edit -m 2 HEAD~1', t=20)
print(f'  文件: {files(d)}   (m2.txt 没了,f1/f2 还在)')
print('== 五:revert 之后再合并同一个 feature:git 认为 F1、F2 已经合并过,不会再带进来')
d = mk('l49d'); run(d, 'git revert --no-edit -m 1 HEAD~1', t=20)
run(d, 'git checkout -q feature'); ci(d, 'F3 功能的第三步(revert 之后新增)', {'f3.txt': 'f3\n'}, t=21); run(d, 'git checkout -q main')
sh(d, 'git merge --no-edit feature 2>&1 | head -3')
print(f'  文件: {files(d)}   ← 只有 f3.txt 回来了,f1.txt、f2.txt 没有回来!')
sh(d, "git log --oneline --graph | sed -E 's/^([*|\\\\/ ]+) [0-9a-f]{7} /\\1 /'")
print('== 六:正确的做法:先 revert 那次 revert(把 F1、F2 的改动恢复回来),再合并')
d = mk('l49e'); run(d, 'git revert --no-edit -m 1 HEAD~1', t=20); rv = out1(d, 'git rev-parse HEAD')
run(d, f'git revert --no-edit {rv}', t=21)
print(f'  revert 了 revert 之后: {files(d)}   (f1、f2 回来了)')
run(d, 'git checkout -q feature'); ci(d, 'F3 新增', {'f3.txt': 'f3\n'}, t=22); run(d, 'git checkout -q main')
sh(d, 'git merge --no-edit feature 2>&1 | head -2')
print(f'  再合并 feature: {files(d)}')
