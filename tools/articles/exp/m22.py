import sys, os; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from ml import *
tee('m22'); reset()
n = Node('m22'); n.start(); c = n.client(); db = c.test
print('== 一:两个字段上建复合索引,每个文档里最多只能有一个字段是数组;一个数组 + 一个标量没问题')
msh(n, 'db.createCollection("t"); db.t.createIndex({a: 1, b: 1})')
msh(n, 'db.t.insertOne({_id: 1, a: [1, 2, 3], b: "x"})')
msh(n, 'db.t.insertOne({_id: 2, a: 1, b: ["x", "y"]})')
print('== 二:两个字段在同一个文档里都是数组:插入被拒绝(错误码 171),索引不会组合成笛卡尔积')
msh(n, 'try { db.t.insertOne({_id: 3, a: [1, 2], b: ["x", "y"]}) } catch (e) { ({code: e.code, name: e.codeName, message: e.message}) }')
msh(n, 'try { db.t.updateOne({_id: 1}, {$set: {b: ["p", "q"]}}) } catch (e) { ({code: e.code, message: e.message}) }', label='db.t.updateOne({_id: 1}, {$set: {b: ["p", "q"]}})    // 把标量改成数组,让 a 和 b 同时是数组')
msh(n, 'db.t.find().toArray()')
print('== 三:已经有“两个数组”的文档时,建这个索引直接失败')
db.u.insert_many([{'_id': 1, 'a': [1, 2], 'b': [3, 4]}, {'_id': 2, 'a': 1, 'b': 2}])
msh(n, 'try { db.u.createIndex({a: 1, b: 1}) } catch (e) { ({code: e.code, name: e.codeName, message: e.message.slice(0, 150)}) }')
msh(n, 'db.u.getIndexes().map(i => i.name)')
print('== 四:数组套数组、子文档里的数组:路径不同就是“不同的数组”')
msh(n, 'db.createCollection("s"); db.s.createIndex({"x.a": 1, "x.b": 1})')
msh(n, 'db.s.insertOne({_id: 1, x: [{a: 1, b: 2}, {a: 3, b: 4}]})', label='db.s.insertOne({x: [{a:1,b:2},{a:3,b:4}]})    // 同一个数组 x 的两个子字段,只算一个数组')
msh(n, 'try { db.s.insertOne({_id: 2, x: [{a: [1, 2], b: [3, 4]}]}) } catch (e) { e.message.slice(0, 120) }', label='db.s.insertOne({x: [{a: [1,2], b: [3,4]}]})    // x.a 与 x.b 都是数组里的数组')
print('== 五:绕开的办法一:拆成两个单字段索引(各自 multikey),查询时按条件选一个;或索引的键用 $all 取交')
db.v.insert_many([{'_id': i, 'a': [i % 10, (i + 1) % 10], 'b': [i % 7, (i + 2) % 7]} for i in range(30000)])
db.v.create_index('a'); db.v.create_index('b')
msh(n, EXJS + 'ex(db.v.find({a: 3, b: 2}).explain("executionStats"))', label='db.v.find({a: 3, b: 2})    // a、b 各一个单字段 multikey 索引')
msh(n, 'db.v.getIndexes().map(i => i.name)')
msh(n, 'db.v.createIndex({a: 1, b: 1})', label='db.v.createIndex({a: 1, b: 1})    // 两个都是数组的集合上建复合索引')
print('== 六:绕开的办法二:把 a、b 的组合展开成子文档数组 pairs,在 pairs.a + pairs.b 上建一个复合索引——查询用 $elemMatch,代价是索引条目变多')
db.w.create_index([('pairs.a', 1), ('pairs.b', 1)])
db.w.insert_many([{'_id': i, 'pairs': [{'a': x, 'b': y} for x in (i % 10, (i + 1) % 10) for y in (i % 7, (i + 2) % 7)]} for i in range(30000)])
msh(n, EXJS + 'ex(db.w.find({pairs: {$elemMatch: {a: 3, b: 2}}}).explain("executionStats"))', label='db.w.find({pairs: {$elemMatch: {a: 3, b: 2}}})    // 把 a、b 的组合展开成 pairs 子文档数组')
print('  v 集合每个文档的 a、b 各 2 个元素;w 集合把它们展开成 2 × 2 = 4 个 {a, b} 子文档:')
msh(n, 'db.w.validate({full: true}).keysPerIndex', label='db.w.validate({full: true}).keysPerIndex')
n.stop()
