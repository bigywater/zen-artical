import sys, os; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from ll import *
tee('l27')
SHORT = "sed -E 's/\\b([0-9a-f]{7})[0-9a-f]{33}\\b/\\1/g'"
# 远程仓库:main、dev、feature/a、feature/b 四个分支,轻量标签 v1,注解标签 v2,以及一个自定义命名空间 refs/pull/1/head
seed = lab('l27seed'); ci(seed, 'm1', {'a': '1\n'}, t=0); ci(seed, 'm2', {'a': '2\n'}, t=1)
run(seed, 'git checkout -q -b dev && echo d > d && git add . && git commit -q -m dev1 && git checkout -q main && git checkout -q -b feature/a && echo a > fa && git add . && git commit -q -m fa1 && git checkout -q main && git checkout -q -b feature/b && echo b > fb && git add . && git commit -q -m fb1 && git checkout -q main', 2)
run(seed, 'git tag v1; git tag -a v2 -m ann', 3); run(seed, 'git update-ref refs/pull/1/head feature/a')
R = LT / 'l27remote.git'; shutil.rmtree(R, ignore_errors=True)
run(seed, f'git clone -q --bare . {R}'); run(seed, f'git --git-dir={R} update-ref refs/pull/1/head feature/a')
def mk(name):
    d = lab(name); run(d, f'git remote add origin {R}'); return d
def lsr(d, pat=''): return out1(d, f"git for-each-ref {pat} --format='%(refname)' | sed 's#^refs/##'").replace('\n', '  ')
print('== 一:远程仓库里有什么(ls-remote),以及 git remote add 写进 config 的默认 refspec')
d = mk('l27a')
sh(d, "git ls-remote origin | sed -E 's/^([0-9a-f]{7})[0-9a-f]{33}/\\1/'")
sh(d, 'git config --get-all remote.origin.fetch; git config remote.origin.url | sed "s#.*/#…/#"')
sh(d, 'git fetch origin 2>&1 | sed -E "s/[0-9a-f]{7}\\.\\.[0-9a-f]{7}/<旧>..<新>/; s#From .*#From <远程>#"')
print(f'  fetch 之后本地的 refs:{lsr(d)}')
print('  (没有 refs/pull/1/head:默认 refspec 只匹配 refs/heads/*;标签是 fetch 的“自动跟随”带来的)')
print('== 二:refspec 的语法 [+]<src>:<dst>;* 只能出现一次,并且两边都得有')
d = mk('l27b')
sh(d, "git fetch -q origin 'refs/heads/feature/*:refs/remotes/o/f/*' 2>&1; git for-each-ref --format='%(refname)' | sed 's#^refs/##'")
sh(d, "git fetch -q origin 'refs/heads/feature/*:refs/remotes/o/x' 2>&1 | head -2")
sh(d, "git fetch -q origin 'refs/pull/1/head:refs/mine/pr1' && git for-each-ref refs/mine --format='%(refname)'")
print('== 三:没有 + 时只允许快进;有 + 才强制覆盖')
sh(d, 'git fetch -q origin main:refs/heads/copy && git branch -v | sed -E "s/ [0-9a-f]{7} / <sha> /"')
run(d, 'git update-ref refs/heads/copy refs/remotes/o/f/a')
sh(d, 'git fetch origin main:refs/heads/copy 2>&1 | sed -E "s#From .*#From <远程>#; s/[0-9a-f]{7}\\.\\.[0-9a-f]{7}/<旧>..<新>/"')
sh(d, 'git fetch origin +main:refs/heads/copy 2>&1 | sed -E "s#From .*#From <远程>#; s/[0-9a-f]{7}\\.\\.\\.?[0-9a-f]{7}/<旧>...<新>/"')
print('== 四:src 为空表示删除(push),dst 为空表示只取回、不创建本地 ref')
sh(d, "git push -q origin copy:refs/heads/tmp1 2>&1; git ls-remote origin refs/heads/tmp1 | sed -E 's/^[0-9a-f]{40}/<sha>/'")
sh(d, "git push origin :refs/heads/tmp1 2>&1 | sed -E 's#To .*#To <远程>#'; git ls-remote origin refs/heads/tmp1 | wc -l; echo '(上一行是删除之后 ls-remote 数出的行数)'")
d = mk('l27c')
sh(d, 'git fetch origin dev 2>&1 | sed -E "s#From .*#From <远程>#"; cat .git/FETCH_HEAD | cut -f1,3 | sed -E "s#^([0-9a-f]{7})[0-9a-f]{33}#\\1#; s# of .*##"; git for-each-ref --format="%(refname)" | sed "s#^refs/##"')
print('  只写 git fetch origin dev(没有 :dst)时,git 仍然顺手更新了 refs/remotes/origin/dev(机会性更新)')
print('== 五:负 refspec(^开头)排除;多个 refspec 叠加')
d = mk('l27d')
sh(d, "git config --add remote.origin.fetch '^refs/heads/feature/*'; git config --get-all remote.origin.fetch; git fetch -q origin 2>&1; git for-each-ref --format='%(refname)' | sed 's#^refs/##' | tr '\\n' ' '; echo")
sh(d, "git config --add remote.origin.fetch '+refs/pull/*/head:refs/remotes/origin/pr/*'; git fetch -q origin 2>&1; git for-each-ref refs/remotes --format='%(refname)' | sed 's#^refs/##' | tr '\\n' ' '; echo")
print('== 六:标签:只取 main 时,指向已取回提交的标签会被自动跟随;--no-tags 关掉它;--tags 取全部')
for nm, extra in [('默认', ''), ('--no-tags', '--no-tags'), ('--tags', '--tags')]:
    dd = mk('l27t'); o = out1(dd, f"git fetch -q {extra} origin 'refs/heads/main:refs/remotes/origin/main' 2>&1; git tag | tr '\\n' ' '")
    print(f'  git fetch {extra:<10} (只取 main)→ 本地标签: {o or "(无)"}')
dd = mk('l27t'); o = out1(dd, "git fetch -q --no-tags origin 'refs/tags/*:refs/tags/*' 2>&1; git tag | tr '\\n' ' '"); print(f"  git fetch 'refs/tags/*:refs/tags/*' → 本地标签: {o}")
print('== 七:push 的 refspec:HEAD:refs/heads/新名字、任意的 ref 名(refs/review/…)')
d = mk('l27e'); run(d, 'git fetch -q origin && git checkout -q -b work origin/main')
sh(d, "git push -q origin HEAD:refs/heads/from-local 2>&1; git push -q origin HEAD:refs/review/42 2>&1; git ls-remote origin 'refs/heads/from-local' 'refs/review/*' | sed -E 's/^[0-9a-f]{40}/<sha>/'")
sh(d, "git config --get push.default || echo '(push.default 未设置,默认 simple)'; git push origin 2>&1 | head -4")
