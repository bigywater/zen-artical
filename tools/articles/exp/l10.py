import sys, os; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from ll import *
tee('l10')
d = lab('l10')
W(d, {'target.txt': 'real\n', 'dir/inner.txt': 'inner\n'})
os.symlink('target.txt', d / 'rel'); os.symlink(str(d / 'target.txt'), d / 'abs'); os.symlink('dir', d / 'dirlink'); os.symlink('nothing.txt', d / 'dangling')
os.symlink('../outside', d / 'dir' / 'up')
print('== 一:四种符号链接(相对、绝对、指向目录、悬空)add 之后:blob 内容就是 readlink 的字符串')
sh(d, 'git add -A && git ls-files -s | grep -v target | grep -v inner')
sh(d, 'for f in rel abs dirlink dangling dir/up; do printf "%-9s readlink=%-34s blob=" $f "$(readlink $f)"; git cat-file -p :$f; echo; done')
print('== 二:提交之后,clone 到别处:相对链接保持有效,绝对链接指回原路径')
ci(d, '链接', t=0)
shutil.rmtree(LT / 'l10clone', ignore_errors=True)
sh(d, 'git clone -q . ../l10clone && cd ../l10clone && for f in rel abs dirlink dangling; do printf "%-9s -> %-28s 能读到内容: " $f "$(readlink $f)"; (cat $f/inner.txt 2>/dev/null || cat $f 2>/dev/null) || echo 否; done')
print('== 三:指向目录的链接:git add ln 把它当链接,git add ln/ 被拒绝')
d2 = lab('l10b'); W(d2, {'real/f.txt': 'f\n'}); os.symlink('real', d2 / 'ln')
sh(d2, 'git add ln; git ls-files -s')
sh(d2, 'git rm -q --cached ln; git add ln/ 2>&1; git ls-files -s')
print('== 四:链接目标变了,git 看到的是“链接 blob 内容变了”,不是目标文件变了')
sh(d, 'ln -sfn dir rel; git status --short; git diff rel')
sh(d, 'git checkout -q -- rel; echo changed >> target.txt; git status --short')
print('== 五:core.symlinks=false:检出时把链接写成一个包含目标路径的普通文件')
shutil.rmtree(LT / 'l10nosym', ignore_errors=True)
sh(d, 'git -c core.symlinks=false clone -q . ../l10nosym && cd ../l10nosym && ls -l rel | cut -c1-10; cat rel; echo "; git status:"; git status --short; git ls-files -s rel')
print('  在 core.symlinks=false 的仓库里修改这个“文件”再提交:')
sh(d, 'cd ../l10nosym && printf "dir" > rel && git add rel && git commit -q -m 改了链接目标 && git ls-files -s rel', t=5)
