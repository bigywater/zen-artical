n0 = objs(d); h0 = out1(d, 'git rev-parse old-name')
sh(d, 'git config --get-regexp "^branch.old-name"; ls .git/refs/heads .git/logs/refs/heads | tr "\\n" " "; echo')
sh(d, 'git branch -m old-name new-name; ls .git/refs/heads .git/logs/refs/heads | tr "\\n" " "; echo; git config --get-regexp "^branch\\.(old|new)-name"; cat .git/HEAD')
print(f'  对象数 {n0} → {objs(d)};分支指向的提交没变: {h0 == out1(d, "git rev-parse new-name")}')
