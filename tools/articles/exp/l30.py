def objs(d): return int(out1(d, "git count-objects -v | awk '/^count:|^in-pack:/{s+=$2} END{print s}'"))
SH = " | sed -E 's/[0-9a-f]{40}/<sha40>/g; s/\\b[0-9a-f]{7}\\b/<sha>/g'"
seed = lab('l30seed'); ci(seed, 'm1', {'a': '1\n'}); R = LT / 'l30remote.git'; shutil.rmtree(R, ignore_errors=True); run(seed, f'git clone -q --bare . {R}')
shutil.rmtree(LT / 'l30', ignore_errors=True); run(LT, f'git clone -q {R} l30'); d = LT / 'l30'
