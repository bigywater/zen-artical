import sys, os; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from ml import *
tee('m26'); reset()
n = Node('m26'); n.start(); c = n.client(); db = c.test
N = 100000
fill(db.t, N, lambda i: {'_id': i, 'a': 0 if i < 10 else 1, 'b': i % 5, 'c': i % 100})
db.t.create_index('a'); db.t.create_index('b'); db.t.create_index('c')
PCS = 'db.t.aggregate([{$planCacheStats: {}}]).toArray().map(e => ({isActive: e.isActive, works: e.works, plan: (function f(p) { return p.stage + (p.indexName ? "(" + p.indexName + ")" : "") + (p.inputStage ? " > " + f(p.inputStage) : "") })(e.cachedPlan), createdFrom: JSON.stringify(e.createdFromQuery.query)}))'
print('== 一:计划缓存按“查询形状”存放:一开始是空的;第一次执行后产生一个 inactive 条目,第二次确认后才变 active')
msh(n, PCS, label='planCacheStats(刚建好索引,还没查过)')
msh(n, 'db.t.find({a: 0, b: 2}).toArray().length', label='第 1 次:db.t.find({a: 0, b: 2})')
msh(n, PCS, label='planCacheStats')
msh(n, 'db.t.find({a: 0, b: 2}).toArray().length', label='第 2 次:同一个形状')
msh(n, PCS, label='planCacheStats')
print('== 二:同一个形状、不同的常量用同一个缓存条目;形状不同(多一个字段、排序不同)是新条目')
msh(n, 'db.t.find({a: 0, b: 4}).toArray().length; db.t.find({a: 0, b: 3}).toArray().length')
msh(n, 'db.t.aggregate([{$planCacheStats: {}}]).toArray().length', label='缓存条目数(同形状不同常量)')
msh(n, 'db.t.find({a: 0, b: 2, c: 7}).toArray().length; db.t.find({a: 0, b: 2}).sort({c: 1}).toArray().length')
msh(n, 'db.t.aggregate([{$planCacheStats: {}}]).toArray().length', label='缓存条目数(加了 c 条件、加了 sort 之后)')
print('== 三:explain 里能看到计划是否来自缓存(isCached)')
msh(n, 'db.t.find({a: 0, b: 1}).toArray().length; var e = db.t.find({a: 0, b: 1}).explain(); e.queryPlanner.winningPlan.isCached', label='db.t.find({a: 0, b: 1}) 再执行一次后 explain().queryPlanner.winningPlan.isCached')
print('== 四:缓存的计划在别的常量上变慢时会被重选:缓存了 a_1 (只有 10 个文档的 a=0),换成 a=1 时它要扫 99,990 个键,works 远超缓存时的 10 倍,触发重新竞选')
msh(n, 'db.setProfilingLevel(2)')
msh(n, 'db.t.find({a: 1, b: 2}).toArray().length', label='db.t.find({a: 1, b: 2})    // a=1 占 99.99% 的文档')
msh(n, 'db.system.profile.find({"command.filter": {a: 1, b: 2}, op: "query"}, {_id: 0, replanned: 1, replanReason: 1, planSummary: 1, keysExamined: 1, docsExamined: 1, planCacheShapeHash: 1}).toArray()', n=30)
msh(n, 'db.setProfilingLevel(0)')
msh(n, PCS, label='planCacheStats(重选之后条目里的计划)', n=30)
print('== 五:索引变化会清空对应集合的缓存条目:创建索引、隐藏索引(hideIndex)之后条目数都归零')
msh(n, 'db.t.aggregate([{$planCacheStats: {}}]).toArray().length', label='缓存条目数(之前)')
msh(n, 'db.t.createIndex({c: 1, b: 1})')
msh(n, 'db.t.aggregate([{$planCacheStats: {}}]).toArray().length', label='缓存条目数(创建索引 c_1_b_1 之后)')
msh(n, 'db.t.find({a: 0, b: 2}).toArray().length; db.t.find({a: 0, b: 2}).toArray().length; db.t.aggregate([{$planCacheStats: {}}]).toArray().length', label='重新执行两次后')
msh(n, 'db.t.hideIndex("c_1_b_1"); db.t.aggregate([{$planCacheStats: {}}]).toArray().length', label='hideIndex 之后的缓存条目数')
print('== 六:手动清理:planCacheClear;以及缓存条目带的信息(候选分数、创建时的执行统计)')
msh(n, 'db.t.find({a: 0, b: 2}).toArray().length; db.t.find({a: 0, b: 2}).toArray().length; var e = db.t.aggregate([{$planCacheStats: {}}]).toArray()[0]; ({keys: Object.keys(e), candidatePlanScores: e.candidatePlanScores, creationWorks: e.creationExecStats && e.creationExecStats.map(x => x.executionStages.works)})', label='一个缓存条目的字段', n=40)
msh(n, 'db.t.getPlanCache().clear(); db.t.aggregate([{$planCacheStats: {}}]).toArray().length', label='db.t.getPlanCache().clear() 之后的条目数')
n.stop()
