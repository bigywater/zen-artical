import sys, time, random, os, json, subprocess, signal, statistics, threading, socket, select, re, collections, struct; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import rl
from rl import *
tee('r70'); R = {}
cl = Cluster(7340, 3, 1, name='c70')
time.sleep(1)
nd = cluster_nodes(cl.nodes[0].c())
masters = sorted([x for x in nd if 'master' in x['flags']], key=lambda x: int(x['slots'][0].split('-')[0]))
replicas = [x for x in nd if 'slave' in x['flags']]
ports = [m['port'] for m in masters]
slot = keyslot('foo'); owner = [m for m in masters if any(int(r.split('-')[0]) <= slot <= int(r.split('-')[-1]) for r in m['slots'])][0]
others = [m for m in masters if m is not owner]
own_c = C(owner['port']); a_c = C(others[0]['port']); b_c = C(others[1]['port'])
rep = [r for r in replicas if r['master'] == owner['id']][0]; rep_c = C(rep['port'])
print(f'槽 {slot}(key "foo")属于主库 {owner["port"]};另外两个主库 {others[0]["port"]}、{others[1]["port"]};{owner["port"]} 的从库是 {rep["port"]}')
print()
print('== 一:MOVED:把请求发给不负责这个槽的节点')
own_c.do('SET', 'foo', 'bar')
sh(own_c, 'GET', 'foo'); sh(a_c, 'GET', 'foo'); sh(b_c, 'SET', 'foo', 'x')
R['moved'] = str(a_c.do('GET', 'foo', raise_err=False))
print()
print('== 二:从库也会回 MOVED,除非先 READONLY')
sh(rep_c, 'GET', 'foo'); sh(rep_c, 'READONLY'); sh(rep_c, 'GET', 'foo')
print()
print('== 三:开始迁移槽 %d:目标节点 IMPORTING,源节点 MIGRATING' % slot)
tgt = others[0]; tgt_c = a_c
tid, oid = tgt['id'], owner['id']
own_c.do('SET', '{foo}exists', 1)
sh(tgt_c, 'CLUSTER', 'SETSLOT', slot, 'IMPORTING', oid)
sh(own_c, 'CLUSTER', 'SETSLOT', slot, 'MIGRATING', tid)
sh(own_c, 'CLUSTER', 'COUNTKEYSINSLOT', slot)
print()
print('== 四:迁移中:源节点上「已存在」的 key 照常服务,「不存在」的 key 回 ASK')
sh(own_c, 'GET', '{foo}exists')
sh(own_c, 'GET', '{foo}notthere')
sh(own_c, 'SET', '{foo}newkey', 1)
sh(own_c, 'MGET', '{foo}exists', '{foo}notthere')
print()
print('== 五:按 ASK 去目标节点:直接发会被打回(MOVED),要先发 ASKING')
sh(tgt_c, 'GET', '{foo}notthere')
sh(tgt_c, 'ASKING'); sh(tgt_c, 'GET', '{foo}notthere')
sh(tgt_c, 'ASKING'); sh(tgt_c, 'SET', '{foo}newkey', 'written-on-target')
print('ASKING 只对紧接着的一条命令有效:')
sh(tgt_c, 'GET', '{foo}newkey')
print()
print('== 六:MIGRATE 把已存在的 key 搬过去;搬完之后源节点上它也变成 ASK')
sh(own_c, 'MIGRATE', '127.0.0.1', tgt['port'], '{foo}exists', 0, 5000)
sh(own_c, 'GET', '{foo}exists')
sh(tgt_c, 'ASKING'); sh(tgt_c, 'GET', '{foo}exists')
print()
print('== 七:把 foo 也搬过去,然后 SETSLOT NODE 完成迁移:之后源节点回 MOVED(永久)')
sh(own_c, 'MIGRATE', '127.0.0.1', tgt['port'], 'foo', 0, 5000)
sh(tgt_c, 'CLUSTER', 'SETSLOT', slot, 'NODE', tid)
sh(own_c, 'CLUSTER', 'SETSLOT', slot, 'NODE', tid)
time.sleep(0.5)
sh(own_c, 'GET', 'foo'); sh(tgt_c, 'GET', 'foo')
save('r70', R); cl.cleanup()
