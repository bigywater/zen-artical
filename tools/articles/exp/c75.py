import sys, os, re, time, subprocess, json; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from dl import *
tee('c75')
img('alpine:3.20')
purge()
def counts():
    c = len(out('ps', '-aq').split()); i = len(out('images', '-aq').split()); v = len(out('volume', 'ls', '-q').split()); n = len(out('network', 'ls', '-q').split())
    return c, i, v, n
def mine():
    return (len(out('ps', '-aq', '--filter', 'label=bwlab=1').split()), len(out('images', '-aq', '--filter', 'label=bwlab=1').split()), len(out('volume', 'ls', '-q', '--filter', 'label=bwlab=1').split()), len(out('network', 'ls', '-q', '--filter', 'label=bwlab=1').split()))
base_all = counts()
print(f'说明:开始前(整个 Docker 里)容器 {base_all[0]}、镜像 {base_all[1]}、卷 {base_all[2]}、网络 {base_all[3]};下面所有 prune 都带 --filter label=bwlab=1,只清理本实验创建的对象(Docker Engine 29.8.2)')
print('== 一:docker container prune')
dk('run', '--name', 'bwlab-c75-exited', *LAB, 'alpine:3.20', 'true')
dk('run', '-d', '--name', 'bwlab-c75-running', *LAB, 'alpine:3.20', 'sleep', '120')
dk('create', '--name', 'bwlab-c75-created', *LAB, 'alpine:3.20')
print(f'  现有:exited、running、created 各一个(都带 bwlab 标签)')
rc, o = dk('container', 'prune', '-f', '--filter', 'label=bwlab=1'); print('  docker container prune -f --filter label=bwlab=1 输出:' + o.strip().replace('\n', ' | ')[:200])
print('  剩下的 bwlab 容器:' + str(sorted(out('ps', '-a', '--filter', 'label=bwlab=1', '--format', '{{.Names}} {{.Status}}').split('\n'))))
dk('rm', '-f', 'bwlab-c75-running')
print('== 二:docker image prune')
d = ctx('c75', {'Dockerfile': 'FROM alpine:3.20\nRUN echo @T@ > /v\n'})
open(d / 'Dockerfile', 'w').write(f'FROM alpine:3.20\nRUN echo v1-{time.time()} > /v\n'); build(d, 'bwlab-c75-img:latest', '--provenance=false', '--sbom=false')
open(d / 'Dockerfile', 'w').write(f'FROM alpine:3.20\nRUN echo v2-{time.time()} > /v\n'); build(d, 'bwlab-c75-img:latest', '--provenance=false', '--sbom=false')
dk('tag', 'bwlab-c75-img:latest', 'bwlab-c75-img:old')
print('  现有:bwlab-c75-img:latest(被 tag 为 :old,别的 bwlab 镜像无)')
print('  docker images --filter dangling=true --filter label=bwlab=1 → ' + str(len(out('images', '-q', '--filter', 'dangling=true', '--filter', 'label=bwlab=1').split())) + ' 个悬空镜像')
rc, o = dk('image', 'prune', '-f', '--filter', 'label=bwlab=1'); print('  docker image prune -f --filter label=bwlab=1:' + o.strip().replace('\n', ' | ')[:220])
print('  之后 bwlab-c75-img 镜像还在吗?' + ('在' if out('images', '-q', 'bwlab-c75-img') else '没了'))
rc, o = dk('image', 'prune', '-a', '-f', '--filter', 'label=bwlab=1'); print('  docker image prune -a -f --filter label=bwlab=1:' + o.strip().replace('\n', ' | ')[:260])
print('  之后 bwlab-c75-img 还在吗?' + ('在' if out('images', '-q', 'bwlab-c75-img') else '没了'))
print('== 三:docker volume prune:匿名卷与命名卷')
dk('volume', 'create', '--label', 'bwlab=1', 'bwlab-c75-named')
dk('run', '--rm', *LAB, '-v', '/anon-data', 'alpine:3.20', 'true')
print('  现有:一个命名卷 bwlab-c75-named(带标签),以及 run --rm -v /anon-data 留下的匿名卷:' + str(len(out('volume', 'ls', '-q', '--filter', 'dangling=true').split())) + ' 个悬空卷(含别人的)')
rc, o = dk('volume', 'prune', '-f', '--filter', 'label=bwlab=1'); print('  docker volume prune -f --filter label=bwlab=1:' + o.strip().replace('\n', ' | ')[:200] + ';bwlab-c75-named 还在吗?' + ('在' if 'bwlab-c75-named' in out('volume', 'ls', '-q') else '没了'))
rc, o = dk('volume', 'prune', '-a', '-f', '--filter', 'label=bwlab=1'); print('  docker volume prune -a -f --filter label=bwlab=1:' + o.strip().replace('\n', ' | ')[:200] + ';bwlab-c75-named 还在吗?' + ('在' if 'bwlab-c75-named' in out('volume', 'ls', '-q') else '没了'))
print('== 四:docker network prune')
dk('network', 'create', '--label', 'bwlab=1', 'bwlab-c75-net')
rc, o = dk('network', 'prune', '-f', '--filter', 'label=bwlab=1'); print('  docker network prune -f --filter label=bwlab=1:' + o.strip().replace('\n', ' | ')[:120])
print('== 五:别人的东西有没有被动到')
end_all = counts()
print(f'  整个 Docker 里的容器 {base_all[0]} → {end_all[0]},镜像 {base_all[1]} → {end_all[1]},卷 {base_all[2]} → {end_all[2]},网络 {base_all[3]} → {end_all[3]}(我的对象已全部清理,数量应与开始时一致)')
print('  本实验的对象还剩:' + str(mine()))
