import sys, time, random, os, json, subprocess, signal; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import rl
from rl import *
tee('r44'); R = {}
n = Node(7144).start(); c = n.c()
for i in range(1, 9): c.do('XADD', 's', f'{i}-0', 'job', f'j{i}')
c.do('XGROUP', 'CREATE', 's', 'g', '0')
print('== 一:工作进程 A(独立进程)读 5 条、ack 2 条、处理第 3 条时被 kill -9')
p = subprocess.Popen([sys.executable, os.path.join(os.path.dirname(os.path.abspath(__file__)), 'w44.py'), '7144'], stdout=subprocess.PIPE, text=True)
for _ in range(4): print(p.stdout.readline().rstrip())
sh(c, 'CLIENT', 'LIST', 'ID', *[x.split()[0][3:] for x in c.do('CLIENT', 'LIST').splitlines() if 'name=worker-A' in x]) if False else None
cl = [l for l in c.do('CLIENT', 'LIST').splitlines() if 'name=worker-A' in l]
print('kill 之前 CLIENT LIST 中的 worker-A:', len(cl), '个连接')
p.kill(); p.wait(); time.sleep(0.3)
cl = [l for l in c.do('CLIENT', 'LIST').splitlines() if 'name=worker-A' in l]
print('kill 之后 CLIENT LIST 中的 worker-A:', len(cl), '个连接')
print()
print('== 二:连接断了,但消费者 A 和它的 PEL 还在,idle 一直在涨')
sh(c, 'XINFO', 'CONSUMERS', 's', 'g')
time.sleep(1.0)
sh(c, 'XPENDING', 's', 'g', '-', '+', 10)
print()
print('== 三:消息不会自动转给别的消费者:B 用 > 读,只拿到没投递过的新消息')
r = sh(c, 'XREADGROUP', 'GROUP', 'g', 'B', 'COUNT', 10, 'STREAMS', 's', '>', show=False)
print('B 用 > 读到的 ID:', [e[0] for e in r[0][1]])
print()
print('== 四:B 用 XCLAIM 主动认领 A 空闲超过 1000 ms 的消息')
sh(c, 'XCLAIM', 's', 'g', 'B', 1000, '3-0', '4-0', '5-0')
sh(c, 'XPENDING', 's', 'g', '-', '+', 10, 'B')
print('(投递次数变成 2:每次被认领 +1)')
print()
print('== 五:XCLAIM 的 min-idle-time 是防重复认领的保护:刚被认领过,马上再认领拿不到')
sh(c, 'XCLAIM', 's', 'g', 'C', 1000, '3-0')
print()
print('== 六:危险操作:XGROUP DELCONSUMER 会直接丢弃该消费者的 PEL')
sh(c, 'XGROUP', 'DELCONSUMER', 's', 'g', 'B')
sh(c, 'XPENDING', 's', 'g')
sh(c, 'XRANGE', 's', '3-0', '3-0')
print('(返回值是被丢弃的 PEL 个数;消息还在流里,但已经没有任何组的 PEL 记着它没处理完)')
save('r44', R); cleanup([n])
