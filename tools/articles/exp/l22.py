import sys, os; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from ll import *
tee('l22')
SH = lambda c: c + " | sed -E 's/[0-9a-f]{40}/<sha>/g'"
d = lab('l22'); ci(d, '主线 1', {'a.txt': '1\n'}, t=0)
run(d, 'git checkout -q -b feature', 1)
f1 = ci(d, '功能 1', {'f.txt': 'f1\n'}, t=1); f2 = ci(d, '功能 2', {'f.txt': 'f2\n', 'g.txt': 'g\n'}, t=2); f3 = ci(d, '功能 3(还没合并)', {'f.txt': 'f3\n'}, t=3)
run(d, 'git checkout -q main', 4)
print('== 一:误删分支 git branch -D feature:三个提交只被这个分支引用')
sh(d, 'git branch -D feature')
sh(d, 'git branch -a; git log --oneline --all')
print('  fsck 找悬空对象(--no-reflogs 忽略 reflog 的保护,等于“假设 reflog 已经过期”):')
o = sh(d, 'git fsck --no-reflogs --lost-found 2>&1')
print(f'  悬空的 commit 就是被删分支的最后一个提交 f3: {f3 in o}')
print('== 二:把它找回来')
sh(d, f'git show -s --format="%h %s" {f3}')
sh(d, f'git branch rescued {f3} && git log --oneline rescued')
print('== 三:dangling 与 unreachable 的区别:dangling 只列出“没人指向的末端”,unreachable 列出所有走不到的对象')
d2 = LT / 'l22'
run(d2, 'git branch -D rescued')
sh(d2, SH('git fsck --no-reflogs 2>&1 | sort | uniq -c'))
sh(d2, SH('git fsck --no-reflogs --unreachable 2>&1 | sed "s/ [0-9a-f]\\{40\\}//" | sort | uniq -c'), n=10)
print('  (3 个提交只有最后一个是 dangling,前两个被它的 parent 链引用着;它们的 tree 和 blob 同理)')
print('== 四:暂存了、没提交就被 reset --hard 冲掉的文件:blob 变成悬空对象,能从 lost-found 里捞回来')
d3 = lab('l22b'); ci(d3, '起点', {'a.txt': '1\n'}, t=0)
W(d3, {'wip.txt': '写了一整天的重要内容\n没提交,只做了 git add\n'}); run(d3, 'git add wip.txt'); wb = out1(d3, 'git rev-parse :wip.txt')
sh(d3, 'git reset --hard -q; ls; git status --short')
sh(d3, 'git fsck --lost-found --no-reflogs 2>&1 | sed -E "s/[0-9a-f]{40}/<sha>/"')
sh(d3, 'ls .git/lost-found/other/ | sed -E "s/[0-9a-f]{40}/<sha>/"; cat .git/lost-found/other/*')
print('  fsck --lost-found 把悬空 blob 写成文件(文件名就是 hash),没有路径信息:')
print(f'  文件名里的 hash 就是原来暂存的 blob: {wb in os.listdir(d3 / ".git" / "lost-found" / "other")}')
print('== 五:git stash drop 之后:stash 本身是 commit,同样能找回')
d4 = lab('l22c'); ci(d4, '起点', {'a.txt': '1\n'}, t=0)
W(d4, {'a.txt': '改了没提交\n'}); sh(d4, 'git stash -q; git stash list; git stash drop')
sh(d4, "git fsck --no-reflogs --unreachable 2>&1 | grep commit | sed -E 's/[0-9a-f]{40}/<sha>/'")
sc = out1(d4, "git fsck --no-reflogs --unreachable 2>&1 | grep commit | awk '{print $3}'").split()[0]
sh(d4, f'git show -s --format="%s | parents=%p" {sc} | sed -E "s/[0-9a-f]{{7}}/<sha>/g"')
sh(d4, f'git stash apply -q {sc} && cat a.txt')
print('== 六:fsck 报告损坏:改坏一个松散对象、删掉一个对象')
d5 = lab('l22d'); ci(d5, '起点', {'a.txt': '内容 A\n', 'b.txt': '内容 B\n'}, t=0)
ba = out1(d5, 'git rev-parse HEAD:a.txt'); bb = out1(d5, 'git rev-parse HEAD:b.txt')
sh(d5, 'git fsck 2>&1; echo "退出码 $?"')
p = d5 / '.git' / 'objects' / ba[:2] / ba[2:]; os.chmod(p, 0o644); raw = bytearray(p.read_bytes()); raw[-3] ^= 0xFF; p.write_bytes(bytes(raw))
sh(d5, "{ git fsck 2>&1; echo \"退出码 $?\"; } | sed -E 's/[0-9a-f]{40}/<sha>/g'")
os.remove(d5 / '.git' / 'objects' / bb[:2] / bb[2:])
sh(d5, "{ git fsck 2>&1; echo \"退出码 $?\"; } | sed -E 's/[0-9a-f]{40}/<sha>/g'", n=12)
