import sys, os; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from ll import *
tee('l5')
d = lab('l5')
c1 = ci(d, '第一次', {'a': '1\n'}, t=0)
cnt = lambda: out1(d, 'find .git/objects -type f | wc -l').strip()
print('== 一:轻量标签只是一个 ref 文件;注解标签还会多一个 tag 对象')
print(f'  打标签之前对象数: {cnt()}')
sh(d, 'git tag light', t=1)
print(f'  git tag light 之后对象数: {cnt()}'); sh(d, 'cat .git/refs/tags/light; git rev-parse HEAD')
sh(d, "git tag -a annot -m '第一个注解标签'", t=2)
print(f'  git tag -a annot 之后对象数: {cnt()}'); sh(d, 'cat .git/refs/tags/annot; git rev-parse HEAD')
print('== 二:tag 对象的原文:指向谁、什么类型、标签名、打标签的人和时间、说明')
sh(d, 'git cat-file -t annot; git cat-file -p annot')
sh(d, 'git cat-file -t light')
print('== 三:同一个标签名,不同写法解出来的是不同的对象')
sh(d, 'for n in light annot annot^{} annot^{commit} annot^{tag}; do printf "%-14s" $n; git rev-parse $n 2>&1 | cut -c1-12; done')
ci(d, '第二次', {'a': '2\n'}, t=3)
sh(d, 'git tag light2', t=3)
print('  新提交上打了轻量标签 light2,git describe 默认只看注解标签,--tags 才看轻量标签:')
sh(d, 'git describe'); sh(d, 'git describe --tags'); sh(d, 'git describe --tags --exact-match HEAD~1')
print('== 四:标签可以指向任何对象——包括另一个标签、tree 和 blob')
sh(d, "git tag -a nested -m '标签的标签' annot", t=4)
sh(d, 'git cat-file -p nested | head -3')
sh(d, "git tag -a ontree -m 'tree 标签' HEAD^{tree}", t=5)
sh(d, 'git cat-file -p ontree | head -3')
sh(d, "git tag -a onblob -m 'blob 标签' HEAD:a", t=6)
sh(d, 'git cat-file -p onblob | head -3')
sh(d, "git for-each-ref refs/tags --format='%(refname:short) → %(objecttype)'")
print('== 五:push --follow-tags 只推带注解的标签;删除标签后 tag 对象还留在对象库里')
sh(d, 'git init -q --bare ../l5bare.git', n=3)
(LT / 'l5bare.git').exists()
sh(d, 'git push -q ../l5bare.git main --follow-tags 2>&1; git --git-dir=../l5bare.git for-each-ref refs/tags --format="%(refname:short)"')
sh(d, 'git tag -d annot nested ontree onblob light', n=8)
sh(d, 'git fsck --lost-found 2>&1 | head -6')
