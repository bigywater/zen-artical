import sys, os, datetime as dt; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from ml import *
tee('m36'); reset()
n = Node('m36'); n.start(); c = n.client(); db = c.test
N = 200000
fill(db.t, N, lambda i: {'_id': i, 'a': i % 5000, 'b': i % 7, 'u': i, 'pad': 'x' * 40})
db.t.create_index('a'); db.t.create_index('u', unique=True); db.t.create_index('b')
Q = '{a: 1234}'
def tq(): return bench(lambda: list(db.t.find({'a': 1234})), 9)
print('== 一:隐藏索引:优化器不再考虑它,但索引仍在。同一条查询在可见 / 隐藏 / 取消隐藏时的计划与耗时')
msh(n, EXJS + f'ex(db.t.find({Q}).explain("executionStats"))', label=f'db.t.find({Q})    // a_1 可见', n=12); t1 = tq()
msh(n, 'db.t.hideIndex("a_1")')
msh(n, EXJS + f'ex(db.t.find({Q}).explain("executionStats"))', label=f'db.t.find({Q})    // a_1 已隐藏', n=12); t2 = tq()
msh(n, 'db.t.unhideIndex("a_1")')
msh(n, EXJS + f'ex(db.t.find({Q}).explain("executionStats"))', label=f'db.t.find({Q})    // 取消隐藏', n=12); t3 = tq()
print(f'  耗时(9 次中位数):可见 {fm(t1)};隐藏 {fm(t2)};取消隐藏 {fm(t3)}')
print('== 二:getIndexes 里隐藏的索引带 hidden: true;$indexStats 的访问计数在隐藏期间不增加')
msh(n, 'db.t.hideIndex("a_1"); db.t.getIndexes().map(i => i.name + (i.hidden ? " (hidden)" : ""))')
msh(n, 'db.t.aggregate([{$indexStats: {}}, {$match: {name: "a_1"}}, {$project: {_id: 0, name: 1, ops: "$accesses.ops"}}])', label='$indexStats(隐藏中)')
db.t.find({'a': 77}).to_list(); db.t.find({'a': 78}).to_list()
msh(n, 'db.t.aggregate([{$indexStats: {}}, {$match: {name: "a_1"}}, {$project: {_id: 0, name: 1, ops: "$accesses.ops"}}])', label='又查了两次 a 之后的 $indexStats(隐藏中,ops 应该没变)')
msh(n, 'db.t.unhideIndex("a_1"); db.t.find({a: 79}).toArray().length; db.t.aggregate([{$indexStats: {}}, {$match: {name: "a_1"}}, {$project: {_id: 0, name: 1, ops: "$accesses.ops"}}])', label='取消隐藏后查一次 a')
print('== 三:隐藏的索引仍然被维护:隐藏期间写入的数据,取消隐藏后立刻可以用索引查到')
msh(n, 'db.t.hideIndex("a_1"); db.t.insertMany([{_id: 9000001, a: 999999, b: 1, u: 9000001}, {_id: 9000002, a: 999999, b: 1, u: 9000002}]).insertedCount')
print(f'  validate 的索引条目数(隐藏中): {db.command("validate", "t", full=True)["keysPerIndex"]}')
msh(n, 'db.t.unhideIndex("a_1"); db.t.find({a: 999999}).toArray().length', label='取消隐藏后 db.t.find({a: 999999})')
msh(n, EXJS + 'ex(db.t.find({a: 999999}).explain("executionStats"))', label='explain', n=12)
print('== 四:对隐藏索引用 hint 会怎样')
msh(n, 'db.t.hideIndex("a_1"); try { db.t.find({a: 1234}).hint("a_1").toArray().length } catch (e) { ({code: e.code, message: e.message.slice(-70)}) }', label='隐藏后 hint("a_1")')
msh(n, 'try { db.t.find({a: 1234}).hint({a: 1}).toArray().length } catch (e) { ({code: e.code, message: e.message.slice(-70)}) }', label='隐藏后 hint({a: 1})')
print('== 五:隐藏不改变索引的约束作用:隐藏的唯一索引仍然拒绝重复;隐藏的 TTL 索引仍然会过期文档')
msh(n, 'db.t.hideIndex("u_1"); try { db.t.insertOne({_id: 9100001, u: 5}) } catch (e) { e.message.slice(0, 100) }', label='隐藏唯一索引 u_1 后插入重复的 u')
db.ttl.create_index('c', expireAfterSeconds=1, name='c_ttl'); c.admin.command('setParameter', 1, ttlMonitorSleepSecs=1)
msh(n, 'db.ttl.hideIndex("c_ttl")')
db.ttl.insert_many([{'_id': i, 'c': dt.datetime.now(dt.timezone.utc) - dt.timedelta(minutes=5)} for i in range(10)]); time.sleep(4)
print(f'  隐藏的 TTL 索引 c_ttl,插入 10 个已过期的文档,4 秒后剩余: {db.ttl.count_documents({})} 个')
print('== 六:限制:不能隐藏 _id 索引;隐藏 / 取消隐藏会清空该集合的计划缓存(见计划缓存一篇)')
msh(n, 'try { db.t.hideIndex("_id_") } catch (e) { e.message }')
msh(n, 'try { db.t.hideIndex("nope") } catch (e) { e.message }', label='hideIndex("nope")')
msh(n, 'db.t.unhideIndex("a_1"); db.t.find({a: 5, b: 5}).toArray().length; db.t.find({a: 5, b: 5}).toArray().length; var n1 = db.t.aggregate([{$planCacheStats: {}}]).toArray().length; db.t.hideIndex("b_1"); [n1, db.t.aggregate([{$planCacheStats: {}}]).toArray().length]', label='[隐藏前缓存条目数, hideIndex 之后的缓存条目数]')
n.stop()
