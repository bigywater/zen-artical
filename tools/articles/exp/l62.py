print('== 三:--force-with-lease:只有远程的 ref 仍然等于“我上次见到的值”才覆盖')
R, cl = setup('l62c'); A, B = cl['A'], cl['B']; ci(B, 'B1', {'b': '1\n'}); run(B, 'git push -q origin main'); ci(A, 'A1 (改写过的)', {'a': '2\n'})
