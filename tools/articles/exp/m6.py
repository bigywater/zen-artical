import sys, os; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from ml import *
from bson.son import SON
tee('m6'); reset()
n = Node('m6'); n.start(); c = n.client(); db = c.test
print('== 一:子文档整体匹配要求字段顺序一致:{sub: {a:1, b:2}} 与 {sub: {b:2, a:1}} 是两个不同的值')
db.t.insert_many([{'_id': 1, 'sub': SON([('a', 1), ('b', 2)])}, {'_id': 2, 'sub': SON([('b', 2), ('a', 1)])}])
msh(n, 'db.t.find({sub: {a: 1, b: 2}}).toArray()')
msh(n, 'db.t.find({sub: {b: 2, a: 1}}).toArray()')
print('== 二:用点号路径分别匹配字段,与顺序无关;顶层字段的顺序也不影响匹配')
msh(n, 'db.t.find({"sub.a": 1, "sub.b": 2}).toArray().map(d => d._id)')
msh(n, 'db.t.find({$and: [{"sub.b": 2}, {"sub.a": 1}]}).toArray().map(d => d._id)')
msh(n, 'db.t.find({$expr: {$eq: ["$sub", {a: 1, b: 2}]}}).toArray().map(d => d._id)')
msh(n, 'db.t.aggregate([{$group: {_id: "$sub", n: {$sum: 1}}}, {$sort: {n: -1}}])')
print('== 三:update 如何改变字段位置:$set 已有字段保持原位,新字段追加到末尾;$unset 后再 $set 会跑到末尾')
db.u.insert_one(SON([('_id', 1), ('a', 1), ('b', 2), ('c', 3)]))
msh(n, 'db.u.updateOne({_id: 1}, {$set: {b: 20}}); db.u.findOne()')
msh(n, 'db.u.updateOne({_id: 1}, {$set: {z: 26}}); db.u.findOne()')
msh(n, 'db.u.updateOne({_id: 1}, {$unset: {a: 1}}); db.u.updateOne({_id: 1}, {$set: {a: 1}}); db.u.findOne()')
msh(n, 'db.u.updateOne({_id: 1}, {$rename: {z: "y"}}); db.u.findOne()')
print('== 四:_id 总是第一个字段:即使插入时写在后面,服务端也会把它挪到最前面')
r = db.command('insert', 'idpos', documents=[SON([('a', 1), ('_id', 99), ('b', 2)])])
print(f'  发送的字段顺序: a, _id, b (用原始 insert 命令)')
msh(n, 'db.idpos.findOne()')
msh(n, 'db.idpos.replaceOne({_id: 99}, {b: 5, a: 4, _id: 99}); db.idpos.findOne()')
print('== 五:mongosh(JavaScript)构造的对象会把像整数的键排到最前面;用 pymongo 读回来才能看清实际存储的顺序')
msh(n, 'db.js.insertOne({_id: 1, b: 1, "2": 2, "1": 1, a: 0}); db.js.findOne()')
print(f'  pymongo 读回 mongosh 插入的文档,字段顺序: {list(db.js.find_one())}')
db.py.insert_one(SON([('_id', 1), ('b', 1), ('2', 2), ('1', 1), ('a', 0)]))
print(f'  pymongo 用 SON 按 b, "2", "1", a 的顺序插入,再用 pymongo 读回,字段顺序: {list(db.py.find_one())}')
msh(n, 'db.py.findOne()', label='db.py.findOne()    // 同一个文档,mongosh 显示时又把整数键排到最前')
print('== 六:字段顺序也影响唯一索引与 $group 的分组键:顺序不同的子文档是不同的键')
db.g.create_index('k', unique=True)
db.g.insert_one({'k': SON([('a', 1), ('b', 2)])})
db.g.insert_one({'k': SON([('b', 2), ('a', 1)])}); print(f'  唯一索引上先后插入 k={{a:1,b:2}} 和 k={{b:2,a:1}}:都成功,集合里 {db.g.count_documents({})} 个文档')
try: db.g.insert_one({'k': SON([('a', 1), ('b', 2)])})
except Exception as e: print(f'  再插入一次 k={{a:1,b:2}}: {str(e)[:110]}')
n.stop()
