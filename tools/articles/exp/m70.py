import sys, os; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from ml import *
from pymongo.errors import PyMongoError, DuplicateKeyError, OperationFailure
tee('m70'); reset()
cl = Cluster('m70', shards=2).start(); c = cl.client(); adm = c.admin
adm.command('balancerStop'); adm.command('enableSharding', 'test')
S = [nd.client() for nd in cl.shards]
c.test.command('create', 'u'); adm.command('shardCollection', 'test.u', key={'uid': 1})
adm.command('split', 'test.u', middle={'uid': 1000}); adm.command('moveChunk', 'test.u', find={'uid': 1500}, to='sh1')
def cnt(coll='u', q=None): return [s.test[coll].count_documents(q or {}) for s in S]
print('== 一:分片键 {uid},手工分成 uid < 1000(在 sh0)和 >= 1000(在 sh1)。在非分片键 email 上建唯一索引')
try: c.test.u.create_index('email', unique=True); print('  成功?')
except OperationFailure as e: print(f'  create_index({{email: 1}}, unique) → code {e.code}: {str(e).split("caused by :: ")[-1][:150]}')
print('== 二:唯一索引必须以分片键为前缀:{uid: 1, email: 1} 可以')
r = c.test.u.create_index([('uid', 1), ('email', 1)], unique=True); print(f'  create_index({{uid: 1, email: 1}}, unique) → {r}')
try: c.test.u.create_index([('email', 1), ('uid', 1)], unique=True); print('  {email, uid} 成功?')
except OperationFailure as e: print(f'  {{email: 1, uid: 1}}(分片键不在前缀)→ code {e.code}: {str(e).split("caused by :: ")[-1][:130]}')
print('== 三:这种唯一索引只保证“同一个 uid 下 email 不重复”,不同 uid 下可以有同样的 email')
c.test.u.insert_one({'uid': 10, 'email': 'a@x.com'})
for lab_, d in [('同一个 uid、同一个 email', {'uid': 10, 'email': 'a@x.com'}), ('不同 uid(在另一个分片)、同一个 email', {'uid': 1500, 'email': 'a@x.com'}), ('同一个分片内不同 uid、同一个 email', {'uid': 20, 'email': 'a@x.com'})]:
    try: c.test.u.insert_one(d); print(f'  {lab_:<34}→ 成功')
    except DuplicateKeyError as e: print(f'  {lab_:<34}→ E11000 {str(e)[:70]}')
print(f'  现在 email = a@x.com 的文档在各分片上的数量: {cnt("u", {"email": "a@x.com"})}(全局并不唯一)')
print('== 四:_id 的唯一性只在单个分片内保证:分片键不是 _id 时,同一个 _id 可以出现在两个分片上')
c.test.u.insert_one({'_id': 'same-id', 'uid': 10, 'email': 'b@x.com'})
try: c.test.u.insert_one({'_id': 'same-id', 'uid': 1600, 'email': 'c@x.com'}); print('  第二个 _id = "same-id"(uid = 1600,落在另一个分片)→ 插入成功')
except DuplicateKeyError: print('  第二个被拒绝')
print(f'  _id = "same-id" 的文档在各分片上的数量: {cnt("u", {"_id": "same-id"})};经 mongos 查 {c.test.u.count_documents({"_id": "same-id"})} 个')
try: c.test.u.insert_one({'_id': 'same-id', 'uid': 20, 'email': 'd@x.com'}); print('  第三个 _id 相同、uid = 20(和第一个同一个分片)→ 成功?')
except DuplicateKeyError as e: print(f'  第三个 _id 相同、uid = 20(和第一个同一个分片)→ E11000')
print('== 五:想要全局唯一就把唯一字段做分片键(或其前缀):shardKey = {email: 1} 时 email 的唯一性是全局的')
c.test.command('create', 'e'); adm.command('shardCollection', 'test.e', key={'email': 1}, unique=True)
adm.command('split', 'test.e', middle={'email': 'm'}); adm.command('moveChunk', 'test.e', find={'email': 'z'}, to='sh1')
c.test.e.insert_one({'email': 'a@x.com'})
try: c.test.e.insert_one({'email': 'a@x.com'}); print('  同样的 email → 成功?')
except DuplicateKeyError: print('  同样的 email → E11000(全局唯一)')
c.test.e.insert_one({'email': 'z@x.com'}); print(f'  a@x.com 与 z@x.com 分别在各分片上的数量: {cnt("e", {"email": "a@x.com"})} {cnt("e", {"email": "z@x.com"})}')
print('== 六:哈希分片键不能做 unique;_id 用哈希做分片键时,同一个 _id 一定落在同一个分片,于是 _id 实际上全局唯一')
c.test.command('create', 'hh')
try: adm.command('shardCollection', 'test.hh', key={'k': 'hashed'}, unique=True); print('  hashed + unique 成功?')
except OperationFailure as e: print(f'  shardCollection(key={{k: "hashed"}}, unique=True) → code {e.code}: {str(e)[:230]}')
c.test.command('create', 'hid'); adm.command('shardCollection', 'test.hid', key={'_id': 'hashed'})
c.test.hid.insert_one({'_id': 123})
try: c.test.hid.insert_one({'_id': 123}); print('  重复 _id → 成功?')
except DuplicateKeyError: print('  _id 用哈希做分片键:重复 _id → E11000(同一个 _id 哈希后总在同一个分片)')
cl.stop()
