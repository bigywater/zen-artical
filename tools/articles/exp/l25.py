import sys, os; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from ll import *
tee('l25')
import ll as _ll
def run(d, cmd, t='now', **k): return _ll.run(d, cmd, t, **k)
def sh(d, cmd, t='now', **k): return _ll.sh(d, cmd, t, **k)
def ci(d, msg, files=None, t='now', **k): return _ll.ci(d, msg, files, t, **k)
def iso(days): return (datetime.datetime.now(datetime.timezone.utc) - datetime.timedelta(days=days)).strftime('%Y-%m-%dT%H:%M:%S+0000')
def at(d, cmd, days=0): return run(d, cmd, t='now', env={'GIT_COMMITTER_DATE': iso(days), 'GIT_AUTHOR_DATE': iso(days)})
SHA = "sed -E 's/\\b[0-9a-f]{7,40}\\b/<sha>/g'"
d = lab('l25')
print('== 一:.git/logs/HEAD 的原始格式:旧 hash、新 hash、操作者、时间戳、时区、制表符、说明')
ci(d, '提交 1', {'a.txt': '1\n'}, t='now'); ci(d, '提交 2', {'a.txt': '2\n'}, t='now')
run(d, 'git checkout -q -b dev', 'now'); run(d, 'git checkout -q main'); run(d, 'git reset -q --hard HEAD~1')
sh(d, "cat .git/logs/HEAD | sed -E 's/^0{40}/<全 0>/; s/[0-9a-f]{40}/<hash>/g; s/ [0-9]{10} /  <时间戳> /'")
print('== 二:每个分支有自己的 reflog,HEAD 也有;用 @{n} 和 @{时间} 引用')
sh(d, 'ls .git/logs .git/logs/refs/heads')
sh(d, "git reflog show main --format='%gd: %gs'")
sh(d, "for i in 0 1 2 3; do printf 'HEAD@{%s} → ' $i; git log -1 --format=%s HEAD@{$i}; done")
sh(d, "{ git log -1 --format=%s 'main@{5.minutes.ago}'; git log -1 --format=%s 'main@{1.hour.ago}'; } 2>&1 | sed -E 's/goes back to .*/goes back to <该 reflog 第一条记录的时间>/'")
print('== 三:哪些操作会写 reflog,说明里写了什么')
d2 = lab('l25b'); ci(d2, '提交 1', {'a.txt': '1\n'}, t='now')
run(d2, 'git checkout -q -b side && echo s > s.txt && git add . && git commit -q -m 侧枝提交 && git checkout -q main && echo m > m.txt && git add . && git commit -q -m 主线提交')
run(d2, 'git merge -q --no-edit side'); run(d2, 'git commit -q --amend -m 改了说明'); run(d2, 'git tag v1'); run(d2, 'git rebase -q side 2>&1')
sh(d2, "git reflog --format='%gd: %gs' | cut -c1-70")
print('== 四:有没有 reflog 取决于 ref 的类型:分支有,标签默认没有;裸仓库默认不记录')
sh(d2, 'ls .git/logs/refs; ls .git/logs/refs/heads; ls .git/logs/refs/tags 2>&1 | head -1; git config core.logAllRefUpdates || echo "(未设置)"')
sh(d2, 'git -c core.logAllRefUpdates=always tag v2; ls .git/logs/refs/tags')
sh(LT, 'rm -rf l25bare.git && git init -q --bare l25bare.git && cd l25bare.git && git config core.logAllRefUpdates || echo "(裸仓库:未设置)"; H=$(git hash-object -w -t tree /dev/null); C=$(GIT_AUTHOR_NAME=a GIT_AUTHOR_EMAIL=a@e GIT_COMMITTER_NAME=a GIT_COMMITTER_EMAIL=a@e git commit-tree $H -m x); git update-ref refs/heads/main $C; ls logs 2>&1 | head -2; echo "(以上是裸仓库 update-ref 之后 logs 目录的内容)"')
print('== 五:过期:HEAD 的 reflog 里造出不同年龄的条目,git reflog expire 默认保留可达的 90 天、不可达的 30 天')
d3 = lab('l25c')
at(d3, 'echo 1 > a.txt && git add . && git commit -q -m A-120天前', 120); at(d3, 'echo 2 > a.txt && git commit -q -am B-100天前', 100)
at(d3, 'git checkout -q -b tmp', 100); at(d3, 'echo 3 > a.txt && git commit -q -am U1-40天前', 40); at(d3, 'echo 4 > a.txt && git commit -q -am U2-20天前', 20)
at(d3, 'git checkout -q main', 10); at(d3, 'git branch -q -D tmp', 10); at(d3, 'echo 5 > a.txt && git commit -q -am C-5天前', 5)
FMT = "git reflog --format='%gd  %gs' --date=relative | sed -E 's/ago\\}/ago}/'"
print('  expire 之前:'); sh(d3, FMT, n=12)
sh(d3, 'git reflog expire --all; echo "(已执行 git reflog expire --all,使用默认过期时间)"')
print('  expire 之后:'); sh(d3, FMT, n=12)
print('== 六:用 reflog 撤销 reset --hard;reflog expire --expire=now 之后就没有退路了')
