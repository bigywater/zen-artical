def ex(n, c): return dk('exec', n, 'sh', '-c', c)[1].strip()
print('== 一:默认容器的 IPv6(Docker Engine 29.8.2)')
dk('run', '-d', '--name', 'bwlab-c56a', *LAB, 'alpine:3.20', 'sleep', '300')
print('  默认 bridge 网络的 EnableIPv6 = ' + out('network', 'inspect', 'bridge', '--format', '{{.EnableIPv6}}'))
print('  容器里 eth0 的 IPv6 地址:' + (ex('bwlab-c56a', "ip -6 addr show dev eth0 | grep inet6 || echo 无") or '无'))
print('  容器里 lo 的 IPv6:' + ex('bwlab-c56a', "ip -6 addr show dev lo | grep inet6 | awk '{print $2}'"))
print('  disable_ipv6(all / eth0):' + ex('bwlab-c56a', 'cat /proc/sys/net/ipv6/conf/all/disable_ipv6 /proc/sys/net/ipv6/conf/eth0/disable_ipv6').replace('\n', ' / '))
print('  默认路由(IPv6):' + (ex('bwlab-c56a', 'ip -6 route | grep default') or '没有'))
print('== 二:--ipv6 的自定义网络')
rc, o = dk('network', 'create', '--label', 'bwlab=1', '--ipv6', 'bwlab-c56v6')
print(f'  docker network create --ipv6(不指定子网):退出码 {rc}')
print('  这个网络的 IPAM:' + out('network', 'inspect', 'bwlab-c56v6', '--format', '{{range .IPAM.Config}}{{.Subnet}} gw={{.Gateway}} ; {{end}}'))
dk('run', '-d', '--name', 'bwlab-c56b', *LAB, '--network', 'bwlab-c56v6', 'alpine:3.20', 'sleep', '300')
dk('run', '-d', '--name', 'bwlab-c56c', *LAB, '--network', 'bwlab-c56v6', 'alpine:3.20', 'sleep', '300')
print('  容器 b 的地址:' + ex('bwlab-c56b', "ip -o addr show dev eth0 | awk '{print $3, $4}'").replace('\n', ' ; '))
ip6c = out('inspect', '--format', '{{(index .NetworkSettings.Networks "bwlab-c56v6").GlobalIPv6Address}}', 'bwlab-c56c')
print(f'  容器 c 的 IPv6 地址:{ip6c}')
rc, o = dk('exec', 'bwlab-c56b', 'ping6', '-c', '2', '-W', '2', ip6c); print(f'  b ping6 c 的 IPv6 地址:退出码 {rc};{o.strip().splitlines()[-1][:80]}')
rc, o = dk('exec', 'bwlab-c56b', 'nslookup', '-type=AAAA', 'bwlab-c56c'); print('  b 查询 bwlab-c56c 的 AAAA 记录:' + ' '.join(l.split()[-1] for l in o.splitlines() if l.startswith('Address') and '#' not in l)[:80] + f'(退出码 {rc})')
rc, o = dk('exec', 'bwlab-c56b', 'ping6', '-c', '1', '-W', '2', 'bwlab-c56c'); print(f'  b ping6 按名字 bwlab-c56c:退出码 {rc};{o.strip().splitlines()[0][:70]}')
print('== 三:IPv6 访问外网')
rc, o = dk('exec', 'bwlab-c56b', 'ping6', '-c', '1', '-W', '3', '2606:4700:4700::1111'); print(f'  容器 b ping6 2606:4700:4700::1111(Cloudflare DNS):退出码 {rc};{(o.strip().splitlines() or ["(无输出)"])[-1][:80]}')
print('  容器 b 的默认 IPv6 路由:' + (ex('bwlab-c56b', 'ip -6 route | grep default') or '没有'))
print('  守护进程配置(虚拟机里的 daemon.json)中默认网络选项的 IPv6 项:' + dk('run', '--rm', '--privileged', '--pid=host', *LAB, 'alpine:3.20', 'nsenter', '-t', '1', '-m', '-u', '-n', '-i', 'sh', '-c', 'grep enable_ipv6 /run/config/docker/daemon.json | tr -d " ,"')[1].strip())
