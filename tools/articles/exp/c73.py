import sys, os, re, time, subprocess, json; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from dl import *
tee('c73')
img('alpine:3.20')
purge()
def vm(cmd):
    rc, o = dk('run', '--rm', '--privileged', '--pid=host', *LAB, 'alpine:3.20', 'nsenter', '-t', '1', '-m', '-u', '-n', '-i', 'sh', '-c', cmd, raw=True)
    return o.strip()
n = 'bwlab-c73'
dk('run', '-d', '--name', n, *LAB, '--cpus', '0.5', '--memory', '100m', '--memory-swap', '100m', '--pids-limit', '50', '--cpu-shares', '512', '--cpuset-cpus', '0-1', '--device-write-bps', '/dev/vda:1mb', 'alpine:3.20', 'sleep', '300'); time.sleep(1)
cid = out('inspect', '--format', '{{.Id}}', n)
hp = out('inspect', '--format', '{{.State.Pid}}', n)
print('== 一:容器的 cgroup 在虚拟机里的位置(Docker Engine 29.8.2)')
print('  /sys/fs/cgroup 的文件系统类型:' + vm("stat -f -c %T /sys/fs/cgroup"))
cg = vm(f"cat /proc/{hp}/cgroup").replace(cid, '<容器ID>')
print('  主进程的 /proc/<pid>/cgroup(相对读取者自己的 cgroup 命名空间):' + cg)
found = vm(f"find /sys/fs/cgroup -maxdepth 4 -type d -name {cid} | head -1")
path = found.replace('/sys/fs/cgroup', '')
print('  在虚拟机的 /sys/fs/cgroup 下找到的目录:/sys/fs/cgroup' + path.replace(cid, '<容器ID>'))
print('  容器的 cgroup 目录里有 ' + vm(f"ls /sys/fs/cgroup{path} | wc -l") + ' 个文件;cgroup.controllers = ' + vm(f"cat /sys/fs/cgroup{path}/cgroup.controllers"))
print('== 二:--cpus / --memory / --pids-limit / --cpu-shares / --cpuset-cpus / --device-write-bps 变成了哪些文件')
for f in ('cpu.max', 'cpu.weight', 'memory.max', 'memory.swap.max', 'pids.max', 'cpuset.cpus', 'cpuset.cpus.effective', 'io.max'):
    print(f'  {f:22s}= ' + vm(f"cat /sys/fs/cgroup{path}/{f} 2>&1").replace('\n', ' ; '))
print('== 三:cgroup.procs 和 docker top')
procs = vm(f"cat /sys/fs/cgroup{path}/cgroup.procs").split()
top = [l.split()[1] for l in dk('top', n)[1].splitlines()[1:]]
print(f'  cgroup.procs:{procs};docker top 的 PID 列:{top};一致吗?{sorted(procs) == sorted(top)}')
print(f'  cgroup.type = {vm(f"cat /sys/fs/cgroup{path}/cgroup.type")};memory.current = {int(vm(f"cat /sys/fs/cgroup{path}/memory.current")) / 1048576:.1f} MiB;pids.current = {vm(f"cat /sys/fs/cgroup{path}/pids.current")}')
print('== 四:docker pause 与 cgroup.freeze')
print('  暂停前:cgroup.freeze = ' + vm(f"cat /sys/fs/cgroup{path}/cgroup.freeze") + ';cgroup.events = ' + vm(f"cat /sys/fs/cgroup{path}/cgroup.events").replace('\n', ' '))
dk('pause', n); time.sleep(0.5)
print('  docker pause 后:cgroup.freeze = ' + vm(f"cat /sys/fs/cgroup{path}/cgroup.freeze") + ';cgroup.events = ' + vm(f"cat /sys/fs/cgroup{path}/cgroup.events").replace('\n', ' '))
dk('unpause', n); time.sleep(0.5)
print('  unpause 后:cgroup.freeze = ' + vm(f"cat /sys/fs/cgroup{path}/cgroup.freeze"))
print('== 五:容器停止后这个 cgroup 目录')
dk('stop', '-t', '1', n); time.sleep(1)
print('  docker stop 之后目录还在吗?' + vm(f"[ -d /sys/fs/cgroup{path} ] && echo 还在 || echo 已删除"))
purge()
