import rl
from rl import *
tee('r43'); R = {}
n = Node(7143).start(); c = n.c()
for i in range(1, 7): c.do('XADD', 's', f'{i}-0', 'job', f'j{i}')
c.do('XGROUP', 'CREATE', 's', 'g', '0')
c.do('XREADGROUP', 'GROUP', 'g', 'a', 'COUNT', 6, 'STREAMS', 's', '>')
print('== 一:XACK 把 ID 从 PEL 里移除,返回成功确认的个数')
sh(c, 'XPENDING', 's', 'g')
sh(c, 'XACK', 's', 'g', '1-0', '2-0')
sh(c, 'XACK', 's', 'g', '1-0')
sh(c, 'XACK', 's', 'g', '99-0')
sh(c, 'XACK', 's', 'g', '3-0', '3-0', '4-0')
sh(c, 'XPENDING', 's', 'g')
print()
print('== 二:XACK 不会删除消息本身')
sh(c, 'XLEN', 's')
sh(c, 'XRANGE', 's', '1-0', '1-0')
print()
print('== 三:PEL 是按组存的:g 里 ack,不影响 g2 里同一条消息')
sh(c, 'XGROUP', 'CREATE', 's', 'g2', '0')
c.do('XREADGROUP', 'GROUP', 'g2', 'a', 'COUNT', 2, 'STREAMS', 's', '>')
sh(c, 'XPENDING', 's', 'g2')
sh(c, 'XACK', 's', 'g', '1-0')
sh(c, 'XACK', 's', 'g2', '1-0')
sh(c, 'XPENDING', 's', 'g2')
print('(XACK 的参数是 key、组、ID,没有消费者名:谁 ack 都行,只要组对)')
print()
print('== 四:ack 之后还能重读吗?XREADGROUP ... 0 只返回还在 PEL 里的')
sh(c, 'XREADGROUP', 'GROUP', 'g', 'a', 'STREAMS', 's', '0')
print()
print('== 五:8.x 新增的 XACKDEL:ack 的同时删除消息;三种引用策略针对"别的组的 PEL 还引用着它"')
c.do('DEL', 't')
for i in range(1, 6): c.do('XADD', 't', f'{i}-0', 'job', f'j{i}')
c.do('XGROUP', 'CREATE', 't', 'g', '0'); c.do('XGROUP', 'CREATE', 't', 'h', '0')
c.do('XREADGROUP', 'GROUP', 'g', 'a', 'STREAMS', 't', '>')
c.do('XREADGROUP', 'GROUP', 'h', 'a', 'STREAMS', 't', '>')
sh(c, 'XACKDEL', 't', 'g', 'ACKED', 'IDS', 1, '1-0')
sh(c, 'XACKDEL', 't', 'g', 'KEEPREF', 'IDS', 1, '2-0')
sh(c, 'XACKDEL', 't', 'g', 'DELREF', 'IDS', 1, '3-0')
sh(c, 'XLEN', 't')
sh(c, 'XPENDING', 't', 'g')
sh(c, 'XPENDING', 't', 'h', '-', '+', 10)
save('r43', R); cleanup([n])
