print('== 六:聚合管道形式的 update(用表达式计算新值)也是 diff;把整个文档换掉($replaceWith)则是整文档替换')
upd('[{$set: {a: {$add: ["$a", 1]}}}]', [{'$set': {'a': {'$add': ['$a', 1]}}}])
