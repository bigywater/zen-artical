print('== 三:原因:index 里每一项都是一个文件路径,没有“目录条目”,空目录没有东西可记')
sh(d, 'git ls-files -s')
et = '4b825dc642cb6eb9a060e54bf8d69288fbee4904'
print('  空 tree 是个合法对象(git 内置识别它),但正常的 git add / commit 不会把它作为子目录放进提交:')
sh(d, f'git mktree < /dev/null; git cat-file -t {et}; git ls-tree {et} | wc -l')
print('== 四:手工造一个带空目录的 tree,看 git 怎么对待它')
sh(d, f"printf '040000 tree {et}\\tempty\\n100644 blob %s\\ta.txt\\n' $(git rev-parse HEAD:a.txt) | git mktree")
t = out1(d, f"printf '040000 tree {et}\\tempty\\n100644 blob %s\\ta.txt\\n' $(git rev-parse HEAD:a.txt) | git mktree")
cm = out1(d, f'git commit-tree {t} -p HEAD -m 带空目录的树')
sh(d, f'git ls-tree {cm}')
sh(d, f'git fsck 2>&1 | head -3')
sh(d, f'git checkout -q {cm} 2>&1; ls -d empty a.txt; git status --short; git checkout -q main')
print('== 五:通行做法:放一个占位文件(.gitkeep 只是约定,名字随意),它的 blob 就是空 blob')
W(d, {'logs/.gitkeep': '', 'empty_dir/.gitkeep': ''})
sh(d, 'git add logs empty_dir && git status --short')
sh(d, 'git ls-files -s logs empty_dir')
sh(d, 'git rev-parse :logs/.gitkeep; git hash-object -t blob /dev/null')
print('  常见做法二:目录里放 .gitignore 忽略自己以外的所有文件:')
W(d, {'cache/.gitignore': '*\n!.gitignore\n', 'cache/tmp1.dat': 'x'})
sh(d, 'git add cache && git status --short cache; git ls-files cache')
