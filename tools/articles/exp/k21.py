def ossl(*a, **kw): return subprocess.run(['openssl', *a], cwd=D, capture_output=True, text=True, **kw)
def mkcsr(name, subj):
    ossl('req', '-new', '-newkey', 'rsa:2048', '-nodes', '-keyout', f'{name}.key', '-out', f'{name}.csr', '-subj', subj)
    return base64.b64encode((D / f'{name}.csr').read_bytes()).decode()
def csr_yaml(name, req, signer='kubernetes.io/kube-apiserver-client', usages=('client auth',), exp=3600):
    return f'apiVersion: certificates.k8s.io/v1\nkind: CertificateSigningRequest\nmetadata: {{name: {name}}}\nspec:\n  request: {req}\n  signerName: {signer}\n  expirationSeconds: {exp}\n  usages: [{", ".join(usages)}]\n'
print(f'集群 {cn};用户证书的签发流程:用户自己生成私钥和 CSR → 提交 CertificateSigningRequest 对象 → 管理员批准 → controller-manager 里的签名者用集群 CA 签发 → 证书写回 status.certificate')

print('== 一:提交 CSR——此时它只是一个等待批准的对象')
req = mkcsr('jane', '/CN=jane/O=devs')
rc, o = k('create', '-f', '-', input=csr_yaml('jane', req)); print(f'  kubectl create csr jane(openssl 生成的 RSA 2048 密钥,Subject CN=jane,O=devs;signerName=kubernetes.io/kube-apiserver-client,expirationSeconds=3600,usages=[client auth]):{o.strip()}')
j = kj('get', 'csr', 'jane')
print(f'  status:conditions={j["status"].get("conditions")};certificate={"(空)" if not j["status"].get("certificate") else "有"};spec.username={j["spec"]["username"]};spec.groups={j["spec"]["groups"]}')
print('  kubectl get csr:' + k('get', 'csr', 'jane')[1].strip().replace('\n', ' | '))
time.sleep(3)
print(f'  等 3 秒之后 certificate 仍然是 {"(空)" if not kj("get", "csr", "jane")["status"].get("certificate") else "有"}——没有批准就没有人签发')

print('== 二:批准之后签发——看证书里写了什么')
t0 = time.time(); rc, o = k('certificate', 'approve', 'jane'); print(f'  kubectl certificate approve jane:{o.strip()}')
v, dt = until(lambda: kj('get', 'csr', 'jane')['status'].get('certificate'), 30, 0.2)
j = kj('get', 'csr', 'jane'); print(f'  {dt:.1f} 秒后 status.certificate 被填上;conditions={[(c["type"], c["reason"]) for c in j["status"]["conditions"]]}')
(D / 'jane.crt').write_bytes(base64.b64decode(j['status']['certificate']))
r = ossl('x509', '-in', 'jane.crt', '-noout', '-subject', '-issuer', '-dates', '-ext', 'extendedKeyUsage,keyUsage'); 
for l in r.stdout.strip().splitlines(): print('    ' + l.strip())
d1 = ossl('x509', '-in', 'jane.crt', '-noout', '-startdate').stdout.strip().split('=')[1]; d2 = ossl('x509', '-in', 'jane.crt', '-noout', '-enddate').stdout.strip().split('=')[1]
p = lambda s: datetime.datetime.strptime(s, '%b %d %H:%M:%S %Y %Z').replace(tzinfo=datetime.timezone.utc)
print(f'  notAfter - notBefore = {(p(d2) - p(d1)).total_seconds():.0f} 秒(请求的 expirationSeconds=3600);notBefore 比签发时刻早 {(datetime.datetime.fromtimestamp(t0 + dt, datetime.timezone.utc) - p(d1)).total_seconds():.0f} 秒左右')

print('== 三:拿这张证书当 kubectl 的用户——身份来自证书的 CN 和 O,权限来自 RBAC')
