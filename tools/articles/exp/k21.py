jk = str(D / 'jane.kubeconfig')
sh('kubectl', 'config', '--kubeconfig', jk, 'set-cluster', 'c', f'--server={srv}', f'--certificate-authority={D / "ca.crt"}', '--embed-certs=true')
sh('kubectl', 'config', '--kubeconfig', jk, 'set-credentials', 'jane', f'--client-certificate={D / "jane.crt"}', f'--client-key={D / "jane.key"}', '--embed-certs=true')
sh('kubectl', 'config', '--kubeconfig', jk, 'set-context', 'jc', '--cluster=c', '--user=jane'); sh('kubectl', 'config', '--kubeconfig', jk, 'use-context', 'jc')
