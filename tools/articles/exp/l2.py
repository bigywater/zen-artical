import sys, os; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from ll import *
tee('l2')
d = lab('l2')
def gh(content, typ='blob'):
    b = content if isinstance(content, bytes) else content.encode()
    return hashlib.sha1(typ.encode() + b' ' + str(len(b)).encode() + b'\0' + b).hexdigest()
print('== 一:blob 的 hash = SHA-1("blob " + 长度 + "\\0" + 内容),手算对照 git hash-object')
for s in ['hello world\n', 'hello world', '']:
    mine = gh(s)
    g = out1(d, f'printf %s {shq(s)} | git hash-object --stdin')
    print(f'  内容 {s!r:16} 手算 {mine}  git {g}  一致={mine == g}')
print('  对比:不加头,直接 SHA-1(内容)')
body = b'hello world\n'
print('   ', hashlib.sha1(body).hexdigest(), '(git 里没有任何对象是这个 hash)')
print('  用 shell 工具复现(不依赖 git):')
sh(d, "printf 'blob 12\\0hello world\\n' | shasum -a 1")
print('  两个众所周知的常数:')
sh(d, 'git hash-object -t blob /dev/null')
sh(d, 'git hash-object -t tree /dev/null')
print('== 二:tree 与 commit 也是同样的公式,只是内容更复杂')
W(d, {'a.txt': 'A\n', 'sub/b.txt': 'B\n'})
sh(d, 'git add -A && git write-tree')
ra = gh('A\n'); rb = gh('B\n')
sub = b'100644 b.txt\0' + bytes.fromhex(rb)
subh = gh(sub, 'tree')
root = b'100644 a.txt\0' + bytes.fromhex(ra) + b'40000 sub\0' + bytes.fromhex(subh)
print('  手算 sub/ 的 tree  :', subh, ' git:', out1(d, 'git ls-tree -d $(git write-tree) sub').split()[2])
print('  手算根 tree        :', gh(root, 'tree'))
tsha = gh(root, 'tree')
msg = f'tree {tsha}\nauthor Alice <alice@example.com> {int(BASE_T.timestamp())} +0000\ncommitter Alice <alice@example.com> {int(BASE_T.timestamp())} +0000\n\n第一次\n'
mine = gh(msg, 'commit')
real = ci(d, '第一次', t=0)
print('  手算 commit        :', mine)
print('  git commit 的真实值:', real, ' 一致=', mine == real)
print('== 三:改一个字节,hash 面目全非;改文件名或权限,blob 的 hash 不变')
a = bytes.fromhex(gh('hello world\n')); b = bytes.fromhex(gh('hello worlD\n'))
diff = sum(bin(x ^ y).count('1') for x, y in zip(a, b))
print('  hello world\\n :', a.hex()); print('  hello worlD\\n :', b.hex()); print(f'  160 位里有 {diff} 位不同({diff / 160:.0%})')
W(d, {'one.txt': 'same\n', 'dir/two.txt': 'same\n'}); W(d, {'x.sh': 'same\n'}, mode=0o755)
sh(d, 'git add -A; git ls-files -s one.txt dir/two.txt x.sh')
print('== 四:同样 12 个字节,放进不同类型的对象,hash 完全不同')
c = 'hello world\n'
for typ in ['blob', 'tree', 'commit', 'tag']:
    print(f'  类型 {typ:<7} → {gh(c, typ)}')
print('  类型只是头部的一个词,但它进了 hash,所以不能把一个 blob 冒充成 tree')
print('== 五:这个 git 用的 SHA-1 实现,以及一个 160 位 hash 的“够不够用”')
sh(d, 'git version --build-options | grep -i sha')
n = 2 ** 80
print(f'  生日界:随机 160 位 hash 要有约 2^80 = {n:.2e} 个对象才有 50% 概率撞车')
print(f'  1 亿个对象(1e8)里出现一对碰撞的概率 ≈ n²/2^161 = {(1e8) ** 2 / 2 ** 161:.2e}')
