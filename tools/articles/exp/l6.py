import sys, os; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from ll import *
tee('l6')
d = lab('l6')
print('== 一:建一条 5 个提交的链,记下每个 commit 的 hash')
cs = []
for i in range(1, 6):
    cs.append(ci(d, f'提交 {i}', {'f.txt': ''.join(f'行 {k}\n' for k in range(1, i + 1))}, t=i))
sh(d, "git log --format='%h %s  parent=%p tree=%t'")
print('== 二:用 filter-branch 把第 2 个提交的说明改一个字(“提交 2” → “提交 二”),看每个 hash 的变化')
old = out1(d, "git log --reverse --format=%H")
run(d, "git filter-branch -f --msg-filter 'sed s/提交\\ 2/提交\\ 二/' HEAD 2>&1 | tail -1", 10)
new = out1(d, "git log --reverse --format=%H")
for i, (o, n) in enumerate(zip(old.split(), new.split()), 1):
    print(f'  提交 {i}: {o[:10]} → {n[:10]}  {"变了" if o != n else "没变"}')
print('  新历史:'); sh(d, "git log --format='%h %s  parent=%p'")
print('== 三:为什么第 3~5 个也变:parent 行是 hash 的一部分,于是改动一路传下去(手算验证第 3 个提交)')
raw = loose(d, new.split()[2])
print('  新的第 3 个提交的原文:'); [print('  | ' + l) for l in raw.split(b'\0', 1)[1].decode().split('\n')]
print('  它的 parent 就是新的第 2 个提交:', new.split()[1] in raw.decode())
print('  tree 呢?只改说明,tree 没变:')
sh(d, "for c in HEAD~4 HEAD~3 HEAD~2 HEAD~1 HEAD; do git rev-parse --short $c^{tree}; done | paste -sd' ' -")
print('== 四:改的是提交 2 里的文件内容(行 2 → 行 二)——提交 2 的 tree 变了,后面的 tree 没变,但后面的 commit hash 照样全变')
d2 = lab('l6b')
for i in range(1, 6): ci(d2, f'提交 {i}', {'f.txt': ''.join(f'行 {k}\n' for k in range(1, i + 1))}, t=i)
o2 = out1(d2, "git log --reverse --format='%H %T'").split('\n')
run(d2, "git filter-branch -f --tree-filter 'if grep -q \"^行 2$\" f.txt && [ $(wc -l < f.txt) -eq 2 ]; then sed -i.bak s/行\\ 2/行\\ 二/ f.txt && rm f.txt.bak; fi' HEAD 2>&1 | tail -1", 10)
n2 = out1(d2, "git log --reverse --format='%H %T'").split('\n')
for i, (a, b) in enumerate(zip(o2, n2), 1):
    (ac, at), (bc, bt) = a.split(), b.split()
    print(f'  提交 {i}: commit {ac[:7]} → {bc[:7]}   tree {at[:7]} → {bt[:7]}')
print('== 五:改最新的提交,前面四个 hash 都保持原样')
d3 = lab('l6c')
for i in range(1, 6): ci(d3, f'提交 {i}', {'f.txt': ''.join(f'行 {k}\n' for k in range(1, i + 1))}, t=i)
before = out1(d3, "git log --reverse --format=%H").split()
run(d3, "git commit --allow-empty -q --amend -m '提交 五(只改最新的)'", 20)
after = out1(d3, "git log --reverse --format=%H").split()
for i, (o, n) in enumerate(zip(before, after), 1): print(f'  提交 {i}: {o[:10]} {"没变" if o == n else "→ " + n[:10]}')
print('  改的位置越靠后,受影响的提交越少:改第 k 个,受影响的是第 k 到第 5 个,共 6-k 个')
