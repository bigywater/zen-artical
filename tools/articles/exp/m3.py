import sys, os; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from ml import *
tee('m3'); reset()
n = Node('m3'); n.start(); c = n.client(); db = c.test
print('== 一:int32、int64、double、Decimal128 的 1 彼此相等:{v: 1} 把四种都查出来,$type 告诉你实际存的是哪种')
db.t.insert_many([{'_id': 'int32', 'v': 1}, {'_id': 'int64', 'v': Int64(1)}, {'_id': 'double', 'v': 1.0}, {'_id': 'decimal', 'v': Decimal128('1')}, {'_id': 'str', 'v': '1'}])
msh(n, 'db.t.find({v: 1}).toArray()')
msh(n, 'db.t.aggregate([{$project: {t: {$type: "$v"}}}])')
msh(n, 'db.t.find({v: NumberLong("1")}).toArray().map(d => d._id)')
print('== 二:大整数的精度:2^53+1 不能用 double 精确表示,查询时 int64 与 double 的比较是精确的,不会“凑巧相等”')
db.big.insert_many([{'_id': 'long_2^53', 'v': Int64(2 ** 53)}, {'_id': 'long_2^53+1', 'v': Int64(2 ** 53 + 1)}, {'_id': 'double_2^53', 'v': float(2 ** 53)}])
msh(n, 'db.big.find({v: 9007199254740992}).toArray().map(d => d._id)')
msh(n, 'db.big.find({v: NumberLong("9007199254740993")}).toArray().map(d => d._id)')
msh(n, 'db.big.find({v: 9007199254740993}).toArray().map(d => d._id)', label='db.big.find({v: 9007199254740993}).toArray().map(d => d._id)    // JS 里这个字面量已经是 9007199254740992')
msh(n, 'db.big.aggregate([{$project: {_id: 1, gt: {$gt: ["$v", 9007199254740992]}}}])')
print('== 三:Decimal128 与 double:0.1 的 double 并不精确等于十进制的 0.1')
db.d.insert_many([{'_id': 'double 0.1', 'v': 0.1}, {'_id': 'decimal 0.1', 'v': Decimal128('0.1')}, {'_id': 'decimal 0.5', 'v': Decimal128('0.5')}, {'_id': 'double 0.5', 'v': 0.5}])
msh(n, 'db.d.find({v: 0.1}).toArray().map(d => d._id)')
msh(n, 'db.d.find({v: Decimal128("0.1")}).toArray().map(d => d._id)')
msh(n, 'db.d.find({v: 0.5}).toArray().map(d => d._id)')
msh(n, 'db.d.aggregate([{$limit: 1}, {$project: {_id: 0, double_sum: {$add: [0.1, 0.2]}, decimal_sum: {$add: [Decimal128("0.1"), Decimal128("0.2")]}}}])')
print('== 四:唯一索引把 1、1.0、NumberLong(1)、Decimal128(1) 当成同一个值')
db.u.create_index('v', unique=True); db.u.insert_one({'v': 1})
for lab_, js in [('1.0', '1.0'), ('NumberLong("1")', 'NumberLong("1")'), ('Decimal128("1")', 'Decimal128("1")'), ('"1"', '"1"')]:
    msh(n, f'try {{ db.u.insertOne({{v: {js}}}); "ok" }} catch (e) {{ e.message.slice(0, 90) }}', label=f'db.u.insertOne({{v: {lab_}}})')
print('== 五:聚合 $sum 的类型提升:int32 溢出变 int64,遇到 double 变 double,遇到 Decimal128 变 Decimal128')
db.s.insert_many([{'_id': 1, 'a': 2147483647, 'b': 1}])
msh(n, 'db.s.aggregate([{$project: {_id: 0, int_plus_int: {$add: ["$a", "$b"]}, t: {$type: {$add: ["$a", "$b"]}}, int_plus_double: {$type: {$add: ["$b", 0.5]}}, int_plus_long: {$type: {$add: ["$b", NumberLong("1")]}}, int_plus_decimal: {$type: {$add: ["$b", Decimal128("1")]}}}}])')
db.m.insert_many([{'v': 2147483647}, {'v': 1}]); db.m2.insert_many([{'v': 1}, {'v': 2}])
msh(n, 'db.m.aggregate([{$group: {_id: null, s: {$sum: "$v"}}}, {$project: {s: 1, t: {$type: "$s"}}}])')
msh(n, 'db.m2.aggregate([{$group: {_id: null, s: {$sum: "$v"}}}, {$project: {s: 1, t: {$type: "$s"}}}])')
print('== 六:$type 的别名 "number" 匹配四种数值类型;大整数写成 JS 数字会悄悄变成 double')
msh(n, 'db.t.find({v: {$type: "number"}}).toArray().map(d => d._id)')
msh(n, 'db.t.find({v: {$type: ["int", "long"]}}).toArray().map(d => d._id)')
msh(n, 'db.x.insertOne({_id: 1, big: 9007199254740993, big2: NumberLong("9007199254740993")}); db.x.aggregate([{$project: {_id: 0, big: 1, t1: {$type: "$big"}, big2: 1, t2: {$type: "$big2"}}}])')
n.stop()
