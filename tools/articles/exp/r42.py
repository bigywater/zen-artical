import sys, time, random, os, json, subprocess, signal; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import rl
from rl import *
tee('r42'); R = {}
n = Node(7142).start(); c = n.c()
for i in range(1, 11): c.do('XADD', 's', f'{i}-0', 'job', f'j{i}')
c.do('XGROUP', 'CREATE', 's', 'g', '0')
print('== 一:读了不 ack:消息进入 PEL(a 读 5 条、b 读 3 条)')
c.do('XREADGROUP', 'GROUP', 'g', 'a', 'COUNT', 5, 'STREAMS', 's', '>')
c.do('XREADGROUP', 'GROUP', 'g', 'b', 'COUNT', 3, 'STREAMS', 's', '>')
sh(c, 'XPENDING', 's', 'g')
print()
print('== 二:XPENDING 明细:[ID, 消费者, 空闲毫秒, 投递次数]')
time.sleep(1.2)
sh(c, 'XPENDING', 's', 'g', '-', '+', 10)
print()
print('== 三:用 XREADGROUP ... 0 重读自己的历史(PEL),投递次数会变吗?')
r = sh(c, 'XREADGROUP', 'GROUP', 'g', 'b', 'STREAMS', 's', '0')
sh(c, 'XPENDING', 's', 'g', '-', '+', 10, 'b')
print()
print('== 四:XPENDING 可以按空闲时间过滤(IDLE)')
sh(c, 'XPENDING', 's', 'g', 'IDLE', 1000, '-', '+', 10, 'a')
print()
print('== 五:NOACK 读取:不进 PEL(用于"丢了也无所谓"的场景)')
c.do('XGROUP', 'CREATE', 's', 'g2', '0')
c.do('XREADGROUP', 'GROUP', 'g2', 'x', 'COUNT', 4, 'NOACK', 'STREAMS', 's', '>')
sh(c, 'XPENDING', 's', 'g2')
print()
print('== 六:PEL 里只存 ID,不存内容:XDEL 掉消息后,PEL 里的条目还在')
sh(c, 'XDEL', 's', '1-0')
sh(c, 'XPENDING', 's', 'g', '-', '+', 10, 'a')
sh(c, 'XREADGROUP', 'GROUP', 'g', 'a', 'STREAMS', 's', '0')
print()
print('== 七:PEL 的内存代价:10 万条消息读了不 ack')
c.do('DEL', 'big'); c.do('XGROUP', 'CREATE', 'big', 'g', '0', 'MKSTREAM')
for i in range(0, 100000, 5000): c.pipeline([['XADD', 'big', '*', 'job', 'payload-%06d' % (i + j)] for j in range(5000)])
m0 = c.do('MEMORY', 'USAGE', 'big', 'SAMPLES', 0)
c.do('XREADGROUP', 'GROUP', 'g', 'w', 'COUNT', 100000, 'STREAMS', 'big', '>')
m1 = c.do('MEMORY', 'USAGE', 'big', 'SAMPLES', 0)
pel = kv(c.do('XINFO', 'GROUPS', 'big')[0])['pending']
print(f'读之前 {m0} B;读完(PEL {pel} 条)后 {m1} B;PEL 增加 {m1-m0} B,平均 {(m1-m0)/pel:.1f} B/条')
R['pel'] = dict(m0=m0, m1=m1, pel=pel)
save('r42', R); cleanup([n])
