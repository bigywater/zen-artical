import sys, os, re, time, subprocess, json, stat; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from dl import *
tee('c23')
img('alpine:3.20')
purge()
UID = os.getuid()
d = ctx('c23', {'Dockerfile': 'FROM alpine:3.20\nRUN mkdir /owned /rootonly && chown 1000:1000 /owned && echo seed > /owned/seed.txt && chown 1000:1000 /owned/seed.txt\n'})
rc, o = build(d, 'bwlab-c23', '--provenance=false', '--sbom=false'); assert rc == 0, o[-300:]
hp = DT / 'c23-bind'; hp.mkdir(exist_ok=True)
def hst(p): s = os.stat(p); return f'uid={s.st_uid} gid={s.st_gid} mode={oct(s.st_mode & 0o777)}'
print(f'== 一:bind mount:容器里的 root 写的文件,宿主机上是谁的(宿主机用户 uid={UID},macOS,Docker Desktop)')
dk('run', '--rm', '-v', f'{hp}:/b', 'alpine:3.20', 'sh', '-c', 'echo hi > /b/by-root.txt; id -u')
print(f'  容器里 root(uid 0)创建的 by-root.txt,在宿主机上:{hst(hp / "by-root.txt")}')
(hp / 'by-host.txt').write_text('h'); os.chmod(hp / 'by-host.txt', 0o640)
rc, o = dk('run', '--rm', '-v', f'{hp}:/b', 'alpine:3.20', 'ls', '-ln', '/b/by-host.txt'); print(f'  宿主机创建的 by-host.txt(宿主机上 {hst(hp / "by-host.txt")}),容器里 ls -ln:{" ".join(o.split()[:4])}')
print('== 二:bind mount:容器里非 root 用户(uid 1000)能写宿主机上的目录吗')
os.chmod(hp, 0o755)
rc, o = dk('run', '--rm', '--user', '1000:1000', '-v', f'{hp}:/b', 'alpine:3.20', 'sh', '-c', 'echo u > /b/by-1000.txt && echo 写成功')
print(f'  宿主机目录 mode 755、属主是宿主机用户:--user 1000 写入 → 退出码 {rc};{o.strip().splitlines()[-1][:100]}')
print(f'  文件在宿主机上:{hst(hp / "by-1000.txt") if (hp / "by-1000.txt").exists() else "没有创建"}')
rc, o = dk('run', '--rm', '-v', f'{hp}:/b', 'alpine:3.20', 'sh', '-c', 'chown 1234:1234 /b/by-root.txt; chmod 600 /b/by-root.txt; ls -ln /b/by-root.txt | awk "{print \\$1, \\$3, \\$4}"')
print(f'  容器里 chown 1234:1234 并 chmod 600 之后,容器里看:{o.strip()};宿主机上:{hst(hp / "by-root.txt")}')
print('== 三:命名卷:权限取决于卷里的目录是谁的')
dk('volume', 'create', '--label', 'bwlab=1', 'bwlab-c23-empty')
rc, o = dk('run', '--rm', '--user', '1000:1000', '-v', 'bwlab-c23-empty:/rootonly', 'bwlab-c23', 'sh', '-c', 'ls -ldn /rootonly | awk "{print \\$1, \\$3, \\$4}"; echo u > /rootonly/f.txt && echo 写成功')
print(f'  镜像里 /rootonly 属主是 root(0:0):空命名卷挂上去,--user 1000 → 退出码 {rc};{" | ".join(l.strip() for l in o.strip().splitlines())[:150]}')
dk('volume', 'create', '--label', 'bwlab=1', 'bwlab-c23-owned')
rc, o = dk('run', '--rm', '--user', '1000:1000', '-v', 'bwlab-c23-owned:/owned', 'bwlab-c23', 'sh', '-c', 'ls -ldn /owned | awk "{print \\$1, \\$3, \\$4}"; stat -c "%u:%g %n" /owned/seed.txt; echo u > /owned/f.txt && echo 写成功')
print(f'  镜像里 /owned 属主是 1000:1000(并含 seed.txt):空命名卷挂上去,--user 1000 → 退出码 {rc};{" | ".join(l.strip() for l in o.strip().splitlines())[:200]}')
rc, o = dk('run', '--rm', '-v', 'bwlab-c23-empty:/v', 'alpine:3.20', 'sh', '-c', 'chown 1000:1000 /v; ls -ldn /v | awk "{print \\$1, \\$3, \\$4}"')
rc, o2 = dk('run', '--rm', '--user', '1000:1000', '-v', 'bwlab-c23-empty:/v', 'alpine:3.20', 'sh', '-c', 'echo u > /v/f.txt && echo 写成功')
print(f'  事后用 root chown 1000:1000 这个卷的根目录({o.strip()}),再用 --user 1000 写入 → {o2.strip()}')
print('== 四:卷里的文件,宿主机(虚拟机里)看到的 uid')
cid = out('run', '-d', '--name', 'bwlab-c23-v', *LAB, '-v', 'bwlab-c23-owned:/owned', 'bwlab-c23', 'sleep', '300')
rc, o = dk('run', '--rm', '--privileged', '--pid=host', *LAB, 'alpine:3.20', 'nsenter', '-t', '1', '-m', '-u', '-n', '-i', 'sh', '-c', 'ls -ln /var/lib/docker/volumes/bwlab-c23-owned/_data | tail -n +2')
print('  Docker Desktop 虚拟机里 /var/lib/docker/volumes/bwlab-c23-owned/_data:' + ' ; '.join(' '.join(l.split()[:4]) + ' ' + l.split()[-1] for l in o.strip().splitlines()))
purge()
