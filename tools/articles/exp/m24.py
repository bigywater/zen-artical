from ml import *
tee('m24'); reset()
n = Node('m24'); n.start(); c = n.client(); db = c.test
E11 = 'try { %s; "ok" } catch (e) { e.message.slice(0, 130) }'
print('== 一:唯一索引里,字段缺失被当成 null——第二个缺失字段的文档就违反唯一性')
msh(n, 'db.a.createIndex({email: 1}, {unique: true})')
msh(n, 'db.a.insertOne({_id: 1, name: "a"}).acknowledged', label='db.a.insertOne({_id: 1, name: "a"})    // 没有 email')
msh(n, E11 % 'db.a.insertOne({_id: 2, name: "b"})', label='db.a.insertOne({_id: 2, name: "b"})    // 又一个没有 email 的文档')
msh(n, E11 % 'db.a.insertOne({_id: 3, email: null})', label='db.a.insertOne({_id: 3, email: null})    // 显式 null,与缺失的冲突')
msh(n, E11 % 'db.a.insertOne({_id: 4, email: "x@x.com"}); db.a.insertOne({_id: 5, email: "y@x.com"})', label='两个不同的非空 email')
print('== 二:唯一 + sparse:缺失字段的文档不进索引,可以有任意多个;但显式的 null 仍然是一个值,会互相冲突')
msh(n, 'db.b.createIndex({email: 1}, {unique: true, sparse: true})')
msh(n, E11 % 'db.b.insertMany([{_id: 1}, {_id: 2}, {_id: 3}])', label='db.b.insertMany([{_id: 1}, {_id: 2}, {_id: 3}])    // 三个缺失 email')
msh(n, E11 % 'db.b.insertOne({_id: 4, email: null})', label='db.b.insertOne({_id: 4, email: null})    // 显式 null:第一个')
msh(n, E11 % 'db.b.insertOne({_id: 5, email: null})', label='db.b.insertOne({_id: 5, email: null})    // 显式 null:第二个')
print('== 三:唯一 + partialFilterExpression: {email: {$type: "string"}}:只有字符串 email 参与唯一性,缺失和 null 都不管')
msh(n, 'db.c.createIndex({email: 1}, {unique: true, partialFilterExpression: {email: {$type: "string"}}})')
msh(n, E11 % 'db.c.insertMany([{_id: 1}, {_id: 2}, {_id: 3, email: null}, {_id: 4, email: null}])', label='缺失 ×2、null ×2')
msh(n, E11 % 'db.c.insertMany([{_id: 5, email: "a@x.com"}, {_id: 6, email: "a@x.com"}], {ordered: true})', label='两个相同的字符串 email')
msh(n, 'db.c.countDocuments({})')
print('== 四:复合唯一索引:每个字段单独缺失按 null 算,整个组合相同才冲突')
msh(n, 'db.d.createIndex({a: 1, b: 1}, {unique: true})')
msh(n, E11 % 'db.d.insertOne({_id: 1, a: 1})', label='db.d.insertOne({a: 1})    // b 缺失')
msh(n, E11 % 'db.d.insertOne({_id: 2, a: 1, b: null})', label='db.d.insertOne({a: 1, b: null})    // 和上一个相同的 (1, null)')
msh(n, E11 % 'db.d.insertOne({_id: 3, a: 1, b: 2})', label='db.d.insertOne({a: 1, b: 2})')
msh(n, E11 % 'db.d.insertOne({_id: 4})', label='db.d.insertOne({})    // a、b 都缺失')
msh(n, E11 % 'db.d.insertOne({_id: 5})', label='再来一个 a、b 都缺失的')
print('== 五:已有重复数据时建唯一索引会失败,错误里给出了其中一个冲突的值')
db.e.insert_many([{'_id': 1, 'k': 'x'}, {'_id': 2, 'k': 'x'}, {'_id': 3}, {'_id': 4}])
msh(n, 'try { db.e.createIndex({k: 1}, {unique: true}) } catch (e) { ({code: e.code, message: e.message.slice(0, 200)}) }')
msh(n, 'db.e.aggregate([{$group: {_id: "$k", ids: {$push: "$_id"}, n: {$sum: 1}}}, {$match: {n: {$gt: 1}}}, {$sort: {n: -1}}])', label='找出重复:$group 后 $match n > 1')
print('== 六:E11000 报错里有什么:索引名、重复的键值;缺失字段的重复键显示成 null')
msh(n, 'try { db.a.insertOne({_id: 9}) } catch (e) { ({code: e.code, keyPattern: e.keyPattern, keyValue: e.keyValue, message: e.message}) }')
msh(n, 'try { db.d.insertOne({_id: 10, a: 1, b: 2}) } catch (e) { ({code: e.code, keyPattern: e.keyPattern, keyValue: e.keyValue}) }')
