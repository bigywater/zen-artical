import sys, os, re, time, subprocess, json; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from dl import *
tee('c25')
img('alpine:3.20')
purge()
H = DT / 'c25'; H.mkdir(exist_ok=True)
(H / 'src').mkdir(); (H / 'src/a.txt').write_text('A'); (H / 'src/sub').mkdir(); (H / 'src/sub/b.txt').write_text('B')
(H / 'one.txt').write_text('one')
cid = out('run', '-d', '--name', 'bwlab-c25', *LAB, 'alpine:3.20', 'sleep', '600')
def ex(c): return dk('exec', cid, 'sh', '-c', c)[1].strip().replace('\n', ' | ')
print('== 一:docker cp 目录时,源路径末尾的 /. 有什么区别(Docker Engine 29.8.2)')
ex('mkdir -p /d1 /d2')
dk('cp', str(H / 'src'), f'{cid}:/d1')
print(f'  docker cp src {{容器}}:/d1(/d1 已存在):/d1 下:{ex("find /d1 -type f | sort")}')
dk('cp', str(H / 'src') + '/.', f'{cid}:/d2')
print(f'  docker cp src/. {{容器}}:/d2(/d2 已存在):/d2 下:{ex("find /d2 -type f | sort")}')
rc, o = dk('cp', str(H / 'src'), f'{cid}:/d3/newname')
print(f'  docker cp src {{容器}}:/d3/newname(/d3 不存在)→ 退出码 {rc};{o.strip()[:100]}')
dk('cp', str(H / 'src'), f'{cid}:/newname')
print(f'  docker cp src {{容器}}:/newname(/newname 不存在,但上级 / 存在):{ex("find /newname -type f | sort")}(目录被改名为 newname)')
print('== 二:拷进去的文件,属主是谁')
dk('cp', str(H / 'one.txt'), f'{cid}:/o1.txt'); dk('cp', '-a', str(H / 'one.txt'), f'{cid}:/o2.txt')
print(f'  宿主机文件属主 uid={os.stat(H / "one.txt").st_uid}:不带 -a:{ex("stat -c %u:%g /o1.txt")};带 -a(archive):{ex("stat -c %u:%g /o2.txt")}')
ex('echo out > /root-file.txt; chown 1234:5678 /root-file.txt')
dk('cp', f'{cid}:/root-file.txt', str(H / 'out1.txt')); st = os.stat(H / 'out1.txt')
rca, oa = dk('cp', '-a', f'{cid}:/root-file.txt', str(H / 'out2.txt')); st2 = os.stat(H / 'out2.txt')
print(f'  容器里属主 1234:5678 的文件拷出来:不带 -a → 宿主机上 uid={st.st_uid};带 -a → uid={st2.st_uid}(带 -a 的 docker cp 退出码 {rca};输出 {oa.strip()[:80] or "无"})')
print('== 三:停止的容器可以拷,挂载的位置呢')
dk('volume', 'create', '--label', 'bwlab=1', 'bwlab-c25v')
(H / 'bind').mkdir()
cid2 = out('run', '-d', '--name', 'bwlab-c25m', *LAB, '-v', 'bwlab-c25v:/vol', '-v', f'{H / "bind"}:/bnd', '--tmpfs', '/tmp1', 'alpine:3.20', 'sleep', '600')
for tgt, label in (('/vol/x.txt', '命名卷 /vol'), ('/bnd/x.txt', 'bind mount /bnd'), ('/tmp1/x.txt', 'tmpfs /tmp1'), ('/plain/x.txt', '普通可写层 /plain')):
    dk('exec', cid2, 'mkdir', '-p', os.path.dirname(tgt))
    rc, o = dk('cp', str(H / 'one.txt'), f'{cid2}:{tgt}')
    seen = dk('exec', cid2, 'cat', tgt)[1].strip()
    print(f'  docker cp 到 {label}:退出码 {rc};容器里读到 = {seen[:40] or "(没有)"}' + (f';{o.strip()[:80]}' if rc else ''))
print(f'  tmpfs 目录里实际有什么:{dk("exec", cid2, "ls", "-A", "/tmp1")[1].strip() or "(空)"}')
print(f'  bind mount 目录在宿主机上有 x.txt 吗?{(H / "bind" / "x.txt").exists()}')
dk('stop', '-t', '1', cid)
rc, o = dk('cp', str(H / 'one.txt'), f'{cid}:/stopped.txt'); print(f'  容器已停止:docker cp 进去 → 退出码 {rc};再 docker cp 出来 → 退出码 {dk("cp", f"{cid}:/stopped.txt", str(H / "st.txt"))[0]},内容 {(H / "st.txt").read_text() if (H / "st.txt").exists() else None}')
print('== 四:符号链接,以及拷出 /etc/hostname 这类 Docker 管理的文件')
cid3 = out('run', '-d', '--name', 'bwlab-c25s', *LAB, 'alpine:3.20', 'sh', '-c', 'ln -s /etc/os-release /lnk; sleep 600')
time.sleep(1)
dk('cp', f'{cid3}:/lnk', str(H / 'lnk1')); dk('cp', '-L', f'{cid3}:/lnk', str(H / 'lnk2'))
print(f'  拷出容器里的符号链接 /lnk:不带 -L → {"符号链接 → " + os.readlink(H / "lnk1") if (H / "lnk1").is_symlink() else "普通文件"};带 -L → {"符号链接" if (H / "lnk2").is_symlink() else "普通文件(" + str((H / "lnk2").stat().st_size) + " 字节)"}')
rc, o = dk('cp', f'{cid3}:/etc/hostname', str(H / 'hn.txt')); print(f'  拷出 /etc/hostname(Docker 为容器生成的文件):退出码 {rc};内容 = {(H / "hn.txt").read_text().strip()};容器 ID 前 12 位 = {cid3[:12]}')
print('== 五:拷贝大文件的速度')
big = H / 'big.bin'; big.write_bytes(os.urandom(64 << 20))
ts = []
for i in range(3):
    t0 = time.time(); dk('cp', str(big), f'{cid3}:/big{i}.bin'); ts.append(ms(t0))
to = []
for i in range(3):
    t0 = time.time(); dk('cp', f'{cid3}:/big{i}.bin', str(H / f'back{i}.bin')); to.append(ms(t0))
print(f'  64 MiB 拷进容器 3 次:{[round(x) for x in ts]} ms(中位数 {med(ts):.0f});拷出 3 次:{[round(x) for x in to]} ms(中位数 {med(to):.0f})')
print(f'  拷回来的文件和原文件一致吗?{(H / "back0.bin").read_bytes() == big.read_bytes()}')
purge()
