import sys, os, re, time, subprocess, json; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from dl import *
tee('c55')
img('alpine:3.20')
purge()
def hosts(n): return dk('exec', n, 'cat', '/etc/hosts')[1].strip()
def mask(t, cid): return t.replace(cid[:12], '<容器ID前12位>')
print('== 一:默认的 /etc/hosts(Docker Engine 29.8.2)')
n = 'bwlab-c55a'
dk('run', '-d', '--name', n, *LAB, 'alpine:3.20', 'sleep', '300')
cid = out('inspect', '--format', '{{.Id}}', n)
ip = out('inspect', '--format', '{{(index .NetworkSettings.Networks "bridge").IPAddress}}', n)
for l in mask(hosts(n), cid).replace(ip, '<容器IP>').splitlines(): print('  ' + l)
print('  hostname 命令:' + mask(dk('exec', n, 'hostname')[1].strip(), cid))
print('== 二:--hostname、--domainname、--add-host')
m = 'bwlab-c55b'
dk('run', '-d', '--name', m, *LAB, '--hostname', 'web01', '--domainname', 'corp.test', '--add-host', 'db.internal:10.9.9.9', '--add-host', 'cache:10.9.9.10', 'alpine:3.20', 'sleep', '300')
ip2 = out('inspect', '--format', '{{(index .NetworkSettings.Networks "bridge").IPAddress}}', m)
for l in hosts(m).replace(ip2, '<容器IP>').splitlines(): print('  ' + l)
print('  hostname = ' + dk('exec', m, 'hostname')[1].strip() + ';hostname -f = ' + dk('exec', m, 'hostname', '-f')[1].strip())
print('  docker inspect HostConfig.ExtraHosts = ' + out('inspect', '--format', '{{json .HostConfig.ExtraHosts}}', m))
print('== 三:/etc/hosts 的优先级高于 DNS')
rc, o = dk('exec', m, 'ping', '-c', '1', '-W', '1', 'db.internal'); print('  ping db.internal(只在 /etc/hosts 里):' + o.splitlines()[0][:60])
m2 = 'bwlab-c55c'
dk('run', '-d', '--name', m2, *LAB, '--add-host', 'github.com:10.9.9.11', 'alpine:3.20', 'sleep', '300')
rc, o = dk('exec', m2, 'ping', '-c', '1', '-W', '1', 'github.com'); print('  --add-host github.com:10.9.9.11 之后,ping github.com:' + o.splitlines()[0][:60])
rc, o = dk('exec', m2, 'nslookup', 'github.com'); print('  同一个容器 nslookup github.com(busybox nslookup 直接问 DNS):' + [l for l in o.splitlines() if l.startswith('Address')][-1])
rc, o = dk('exec', 'bwlab-c55a', 'ping', '-c', '1', '-W', '1', 'github.com'); print('  对比:没加 --add-host 的容器 ping github.com:' + o.splitlines()[0][:60])
print('== 四:同名多条、容器里改 /etc/hosts')
m3 = 'bwlab-c55d'
dk('run', '-d', '--name', m3, *LAB, '--add-host', 'multi:10.9.9.20', '--add-host', 'multi:10.9.9.21', 'alpine:3.20', 'sleep', '300')
print('  --add-host multi:10.9.9.20 --add-host multi:10.9.9.21 → /etc/hosts 里 multi 的行:' + ' ; '.join(l.strip() for l in hosts(m3).splitlines() if 'multi' in l))
rc, o = dk('exec', m3, 'ping', '-c', '1', '-W', '1', 'multi'); print('  ping multi 解析到:' + o.splitlines()[0][:60])
dk('exec', m3, 'sh', '-c', 'echo "10.9.9.99 edited.local" >> /etc/hosts')
print('  容器里追加 10.9.9.99 edited.local 后,docker exec cat 能看到吗?' + ('能' if 'edited.local' in hosts(m3) else '不能'))
dk('restart', '-t', '1', m3)
print('  docker restart 之后 edited.local 还在吗?' + ('在' if 'edited.local' in hosts(m3) else '不在') + ';--add-host 的 multi 还在吗?' + ('在' if 'multi' in hosts(m3) else '不在'))
purge()
