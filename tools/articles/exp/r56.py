import sys, time, random, os, json, subprocess, signal, statistics, threading, socket, select; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import rl
from rl import *
tee('r56'); R = {}
M = Node(7162, name='m56', conf={'repl-backlog-size': '16kb'}).start(); Rp = Node(7163, name='r56', conf={'replicaof': '127.0.0.1 7164'})
px = Proxy(7164, 7162); Rp.start(); m, r = M.c(), Rp.c(); wait_link(r)
m.do('SET', 'a', 1)
time.sleep(0.2)
print('== 一:默认的只读从库')
sh(r, 'CONFIG', 'GET', 'replica-read-only')
sh(r, 'GET', 'a')
for cmd in (['SET', 'a', 2], ['DEL', 'a'], ['EXPIRE', 'a', 10], ['INCR', 'n'], ['FLUSHALL'], ['EVAL', "return redis.call('SET','z',1)", 0], ['PUBLISH', 'ch', 'x'], ['EVAL_RO', "return redis.call('GET','a')", 0]):
    sh(r, *cmd)
print()
print('== 二:replica-read-only no:从库可以写,但主库看不到,也不会被同步回主库')
sh(r, 'CONFIG', 'SET', 'replica-read-only', 'no')
sh(r, 'SET', 'local', 'only-on-replica'); sh(r, 'SET', 'a', 'changed-on-replica')
print('主库 GET a =', m.do('GET', 'a'), '  主库 GET local =', m.do('GET', 'local'))
print('从库 GET a =', r.do('GET', 'a'), '  从库 GET local =', r.do('GET', 'local'))
print()
print('== 三:主库再写同一个 key:从库本地的改动被覆盖;但只在主库没写的 key 上,本地数据会一直留着')
m.do('SET', 'a', 'from-master'); time.sleep(0.2)
print('从库 GET a =', r.do('GET', 'a'), '  从库 GET local =', r.do('GET', 'local'))
print('dbsize 主/从:', m.do('DBSIZE'), r.do('DBSIZE'))
print()
print('== 四:从库上写带 TTL 的 key:从库会自己过期它(而不是等主库发 DEL)')
r.do('SET', 'ttl_local', 'v', 'PX', 300); time.sleep(0.6)
print('600 ms 后从库 GET ttl_local =', r.do('GET', 'ttl_local'))
print()
print('== 五:全量重同步会清掉从库本地写入:断线期间主库写 100 KB,超过 backlog')
px.cut(); time.sleep(0.4)
m.pipeline([['SET', f'p{i}', 'x' * 100] for i in range(1000)])
s0 = repl_stats(m); px.resume(); time.sleep(1.5); wait_link(r); time.sleep(0.3); s1 = repl_stats(m)
print(f'主库 sync_full +{s1["sync_full"]-s0["sync_full"]}, partial_ok +{s1["sync_partial_ok"]-s0["sync_partial_ok"]}')
print('从库 GET local =', r.do('GET', 'local'), '  dbsize 主/从:', m.do('DBSIZE'), r.do('DBSIZE'))
R['full_wipe'] = r.do('GET', 'local') is None
print()
print('== 六:部分重同步则不会清:断线期间只写少量')
r.do('SET', 'local2', 'v')
px.cut(); time.sleep(0.4); m.do('SET', 'q', 1)
s0 = repl_stats(m); px.resume(); time.sleep(1.5); wait_link(r); time.sleep(0.3); s1 = repl_stats(m)
print(f'主库 sync_full +{s1["sync_full"]-s0["sync_full"]}, partial_ok +{s1["sync_partial_ok"]-s0["sync_partial_ok"]}')
print('从库 GET local2 =', r.do('GET', 'local2'), '  主库 GET local2 =', m.do('GET', 'local2'))
R['partial_keep'] = r.do('GET', 'local2')
save('r56', R); px.cut(); cleanup([M, Rp])
