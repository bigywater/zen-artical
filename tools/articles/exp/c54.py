def vm(cmd):
    rc, o = dk('run', '--rm', '--privileged', '--pid=host', *LAB, 'alpine:3.20', 'nsenter', '-t', '1', '-m', '-u', '-n', '-i', 'sh', '-c', cmd, raw=True)
    return o.strip()
def rconf(n): return dk('exec', n, 'sh', '-c', 'grep -v "^#" /etc/resolv.conf | grep -v "^$"')[1].strip().replace('\n', ' ; ')
