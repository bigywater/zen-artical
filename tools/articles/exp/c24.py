import sys, os, re, time, subprocess, json; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from dl import *
tee('c24')
img('alpine:3.20')
purge()
def sh(cid, c): return dk('exec', cid, 'sh', '-c', c)
print('== 一:--tmpfs 默认多大,加 size= 之后呢(Docker Engine 29.8.2)')
cid = out('run', '-d', '--name', 'bwlab-c24a', *LAB, '--tmpfs', '/t1', '--tmpfs', '/t2:size=10m', 'alpine:3.20', 'sleep', '600')
for t in ('/t1', '/t2'):
    rc, o = sh(cid, f"grep ' {t} ' /proc/mounts | awk '{{print $3, $4}}'; df -k {t} | tail -1 | awk '{{print $2}}'")
    l = o.strip().splitlines(); print(f'  {t}:挂载类型与选项 = {l[0]};df 显示总大小 {int(l[1]) // 1024} MiB')
mem = int(out('exec', cid, 'sh', '-c', "awk '/MemTotal/ {print $2}' /proc/meminfo")) // 1024
print(f'  虚拟机(容器看到的)MemTotal = {mem} MiB;/t1 默认大小 = 其一半吗?{abs(int(sh(cid, "df -k /t1 | tail -1 | awk \'{print $2}\'")[1].strip()) // 1024 - mem // 2) < 4}')
print('== 二:写满 size=10m 的 tmpfs')
rc, o = sh(cid, 'dd if=/dev/zero of=/t2/big bs=1M count=20 2>/tmp/dd.err; echo "dd 退出码 $?"; cat /tmp/dd.err | grep -v "^$" | head -3; ls -l /t2/big | awk "{print \\$5}"')
print('  dd 写 20 MiB 到 /t2(size=10m):' + ' | '.join(l.strip() for l in o.strip().splitlines()))
print('== 三:容器重启之后,tmpfs 里的数据还在吗(对比容器可写层)')
sh(cid, 'echo tmp > /t1/f.txt; echo layer > /layer.txt')
dk('restart', '-t', '1', cid)
rc, o = sh(cid, 'cat /layer.txt; ls /t1 | wc -l'); print(f'  docker restart 之后:可写层里的 /layer.txt = {o.split()[0]};/t1 里的文件数 = {o.split()[1]}')
print('== 四:tmpfs 占的是内存:写 100 MiB 前后,容器的内存用量(cgroup memory.current)')
cid2 = out('run', '-d', '--name', 'bwlab-c24b', *LAB, '--tmpfs', '/t', 'alpine:3.20', 'sleep', '600')
def cur(c): return int(out('exec', c, 'cat', '/sys/fs/cgroup/memory.current')) / 1048576
b = cur(cid2); sh(cid2, 'dd if=/dev/zero of=/t/f bs=1M count=100 2>/dev/null'); a = cur(cid2)
print(f'  写入前 {b:.1f} MiB → 写入 100 MiB 后 {a:.1f} MiB(增加 {a - b:.1f} MiB)')
sh(cid2, 'rm /t/f'); print(f'  删掉文件后 {cur(cid2):.1f} MiB')
bl = cur(cid2); sh(cid2, 'dd if=/dev/zero of=/layer.bin bs=1M count=100 2>/dev/null'); al = cur(cid2)
print(f'  对比:同样 100 MiB 写到容器可写层 /layer.bin:{bl:.1f} → {al:.1f} MiB(增加 {al - bl:.1f} MiB;页缓存也会计入)')
print('== 五:有 --memory 限制时,tmpfs 写满会怎样')
rc, o = dk('run', '--name', 'bwlab-c24c', *LAB, '--memory', '64m', '--memory-swap', '64m', '--tmpfs', '/t:size=200m', 'alpine:3.20', 'sh', '-c', 'dd if=/dev/zero of=/t/f bs=1M count=150 2>/dev/null; echo "dd 退出码 $?"')
st = out('inspect', '--format', '{{.State.ExitCode}} {{.State.OOMKilled}}', 'bwlab-c24c')
print(f'  --memory 64m、tmpfs size=200m,往里写 150 MiB:docker run 退出码 {rc};输出:{o.strip() or "(无)"};容器 ExitCode OOMKilled = {st}')
print('== 六:--mount 写法与目录权限')
for opt in ('type=tmpfs,destination=/m1', 'type=tmpfs,destination=/m2,tmpfs-mode=0700,tmpfs-size=5m'):
    rc, o = dk('run', '--rm', '--mount', opt, 'alpine:3.20', 'sh', '-c', f"ls -ld {opt.split('destination=')[1].split(',')[0]} | awk '{{print $1}}'")
    print(f'  --mount {opt} → 目录权限 {o.strip()}')
purge()
