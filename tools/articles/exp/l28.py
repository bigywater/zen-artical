import sys, os; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from ll import *
import ll as _ll
tee('l28')
def run(d, cmd, t='now', **k): return _ll.run(d, cmd, t, **k)
def sh(d, cmd, t='now', **k): return _ll.sh(d, cmd, t, **k)
def ci(d, msg, files=None, t='now', **k): return _ll.ci(d, msg, files, t, **k)
_names = {}
def nm(h): return _names.setdefault(h, f'提交{len(_names) + 1}') if h and h != '(不存在)' else h
def rp(d, spec): return nm(out1(d, f'git rev-parse --short {spec} 2>/dev/null') or '(不存在)')
seed = lab('l28seed'); ci(seed, 'm1', {'a': '1\n'}); R = LT / 'l28remote.git'; shutil.rmtree(R, ignore_errors=True); run(seed, f'git clone -q --bare . {R}')
for n in ['l28A', 'l28B']: shutil.rmtree(LT / n, ignore_errors=True); run(LT, f'git clone -q {R} {n}')
A = LT / 'l28A'; B = LT / 'l28B'
sh(A, 'git config user.name Alice; git config user.email a@e', show=False)
print('== 一:本地的 origin/main 只在“和远程通信”的命令里更新:fetch、pull、push 会,commit、checkout、ls-remote 不会')
def o(d): return rp(d, 'origin/main')
def step_(label, d, cmd):
    before = o(d); run(d, cmd); after = o(d); print(f'  {label:<44} origin/main: {before} → {after}  {"变了" if before != after else "没变"}')
print(f'  起点:A 的 origin/main = {o(A)};B 的 origin/main = {o(B)}')
ci(A, 'A 的提交 2', {'a': '2\n'}); step_('A: git commit(本地提交)', A, 'true')
step_('A: git ls-remote origin', A, 'git ls-remote origin')
step_('A: git checkout -b x; git checkout main', A, 'git checkout -q -b x; git checkout -q main')
step_('A: git push origin main', A, 'git push -q origin main')
print('== 二:此时远程已有提交 2,B 还不知道;git status 的落后提示也要等 fetch 才出现'); print('  B 的缓存:'); print(f'    B 的 origin/main = {o(B)}(远程的 main 是 {nm(out1(B, "git ls-remote origin main | cut -c1-7"))})')
sh(B, 'git status -sb | head -1; echo "(B 的 git status 仍然说 up to date,因为它只和自己缓存的 origin/main 比较)"')
step_('B: git fetch', B, 'git fetch -q')
sh(B, 'git status -sb | head -1')
print('== 三:push 失败时不更新;push 到不同名字的远程分支更新对应的 origin/<名字>')
ci(A, 'A 的提交 3', {'a': '3\n'}); run(A, 'git push -q origin main')
ci(B, 'B 的提交(基于旧的 origin/main)', {'b': 'b\n'})
b0 = o(B)
print('  B 推送(远程已有 A 的提交 3,B 没有):')
sh(B, "git push origin main 2>&1 | grep -E 'rejected|error'")
print(f'  B 的 origin/main 推送前后: {b0} → {o(B)}(没变:push 被拒绝,不会更新)')
sh(B, 'git push -q origin main:refs/heads/b-copy; git for-each-ref refs/remotes --format="%(refname:short)" | tr "\\n" " "; echo')
print('== 四:远程删了分支,本地的 origin/b-copy 还在(stale);fetch --prune 才删')
run(A, 'git push -q origin :refs/heads/b-copy')
sh(B, 'git fetch -q; git branch -r | tr "\\n" " "; echo; git remote show origin 2>&1 | grep -E "stale|tracked" | head -3')
sh(B, 'git fetch --prune 2>&1 | sed -E "s#From .*#From <远程>#"; git branch -r | tr "\\n" " "; echo')
sh(B, 'git config fetch.prune true; git config --get fetch.prune')
print('== 五:refs/remotes/origin/HEAD:clone 时设置,指向远程的默认分支;远程改了默认分支它不会自己变')
sh(B, 'cat .git/refs/remotes/origin/HEAD; git symbolic-ref refs/remotes/origin/HEAD')
run(A, 'git push -q origin main:refs/heads/trunk'); run(R, 'git symbolic-ref HEAD refs/heads/trunk')
sh(B, 'git fetch -q; git symbolic-ref refs/remotes/origin/HEAD; echo "(fetch 之后仍是 main)"; git remote set-head origin -a; git symbolic-ref refs/remotes/origin/HEAD')
print('== 六:remote-tracking ref 也有 reflog,记录 fetch / push 带来的每次移动')
sh(B, "git reflog show origin/main --format='%gd: %gs' | head -6")
sh(B, "git log -1 --format=%s 'origin/main@{1}'")
